// TestBuildBankRegionCapsAndPresentPointersOnly: the region never exceeds its line/byte reserve, points
// only at typed files that actually exist, and overflow entries get a "… N more" marker.
func TestBuildBankRegionCapsAndPresentPointersOnly(t *testing.T) {
	migrateConfig1(t)
	dir := t.TempDir()
	write(t, filepath.Join(dir, "activeContext.md"), "# Active\n")
	write(t, filepath.Join(dir, "progress.md"), "# Progress\n")
	var b strings.Builder
	for i := 1; i <= 50; i++ {
		fmt.Fprintf(&b, "## 2026-01-%02d — decision %d\n\nwhy: because\n\n", i%28+1, i)
	}
	write(t, filepath.Join(dir, "decisionLog.md"), b.String())

	now := time.Date(2026, 1, 1, 0, 0, 0, 0, time.UTC)
	region := buildBankRegion(dir, now)

	if n := lineCount(region); n > BankRegionMaxLines {
		t.Errorf("region has %d lines, want <= %d:\n%s", n, BankRegionMaxLines, region)
	}
	if len(region) >= BankRegionMaxBytes {
		t.Errorf("region is %d bytes, want < %d", len(region), BankRegionMaxBytes)
	}
	for _, present := range []string{"[activeContext](activeContext.md)", "[progress](progress.md)"} {
		if !strings.Contains(region, present) {
			t.Errorf("region missing present-file pointer %q:\n%s", present, region)
		}
	}
	for _, absent := range []string{"(projectContext.md)", "(conventions.md)", "(sessionHistory.md)"} {
		if strings.Contains(region, absent) {
			t.Errorf("region pointed at an absent typed file %q:\n%s", absent, region)
		}
	}
	if !strings.Contains(region, "more entries (memory search)") {
		t.Errorf("region missing the overflow marker for 50 decisions:\n%s", region)
	}
	if !strings.HasPrefix(region, bankRegionBegin) || !strings.Contains(region, bankRegionEnd) {
		t.Errorf("region missing its markers:\n%s", region)
	}
}

// TestWriteBankRegionInsertsReplacesAndRefuses: absent -> inserted at top; present -> replaced in place
// with bytes outside the region untouched; a malformed region (two begin markers) refuses the write.
func TestWriteBankRegionInsertsReplacesAndRefuses(t *testing.T) {
	migrateConfig1(t)
	dir := t.TempDir()
	now := time.Date(2026, 1, 1, 0, 0, 0, 0, time.UTC)

	changed, err := writeBankRegion(dir, now)
	if err != nil || !changed {
		t.Fatalf("insert into an absent file: changed=%v err=%v", changed, err)
	}
	first := mustRead(t, filepath.Join(dir, NativeIndexFile))
	if !strings.HasPrefix(first, bankRegionBegin) {
		t.Fatalf("region not inserted at the top:\n%s", first)
	}

	withTrailer := first + "hand-written trailing notes\n"
	write(t, filepath.Join(dir, NativeIndexFile), withTrailer)
	changed, err = writeBankRegion(dir, now.Add(24*time.Hour))
	if err != nil {
		t.Fatal(err)
	}
	if !changed {
		t.Error("a date-bumped region must report changed")
	}
	second := mustRead(t, filepath.Join(dir, NativeIndexFile))
	if !strings.HasSuffix(second, "hand-written trailing notes\n") {
		t.Errorf("bytes outside the region changed:\n%s", second)
	}

	if changed, err = writeBankRegion(dir, now.Add(24*time.Hour)); err != nil || changed {
		t.Errorf("an identical rewrite must report no change: changed=%v err=%v", changed, err)
	}

	broken := second + bankRegionBegin + " generated by claude-code memory index 2026-01-01 -->\nextra\n"
	write(t, filepath.Join(dir, NativeIndexFile), broken)
	if _, err := writeBankRegion(dir, now); !errors.Is(err, errBankRegion) {
		t.Errorf("writeBankRegion on a doubled-marker file err = %v, want errBankRegion", err)
	}
	if got := mustRead(t, filepath.Join(dir, NativeIndexFile)); got != broken {
		t.Error("a refused rewrite must leave every byte in place")
	}
}

// TestBuildCatalogListsRepoRowsAndCapsGlobal: every repo store gets a row, and the global entry
// section caps at catalogGlobalMax with an overflow marker.
func TestBuildCatalogListsRepoRowsAndCapsGlobal(t *testing.T) {
	migrateConfig1(t)
	a := gitRepo(t, t.TempDir(), "alpha")
	b := gitRepo(t, t.TempDir(), "beta")
	da, err := EnsureRepoDir(a)
	if err != nil {
		t.Fatal(err)
	}
	if _, err := EnsureRepoDir(b); err != nil {
		t.Fatal(err)
	}
	write(t, filepath.Join(da, "projectContext.md"), "# Project\n\nalpha project, routes ssh deploys\n")

	var conv strings.Builder
	conv.WriteString("# Conventions\n\n")
	for i := 1; i <= 15; i++ {
		fmt.Fprintf(&conv, "- rule %d\n", i)
	}
	write(t, filepath.Join(StoreDir(), "conventions.md"), conv.String())

	now := time.Date(2026, 1, 1, 0, 0, 0, 0, time.UTC)
	catalog, err := BuildCatalog(now)
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{"alpha", "beta", "alpha project, routes ssh deploys"} {
		if !strings.Contains(catalog, want) {
			t.Errorf("catalog missing %q:\n%s", want, catalog)
		}
	}
	lines := 0
	for _, l := range strings.Split(catalog, "\n") {
		if strings.HasPrefix(l, "- rule ") {
			lines++
		}
	}
	if lines > catalogGlobalMax {
		t.Errorf("catalog carried %d global rule lines, want <= %d", lines, catalogGlobalMax)
	}
	if !strings.Contains(catalog, "more (memory search)") {
		t.Error("catalog missing the global overflow marker")
	}
}
