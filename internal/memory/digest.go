// Digest bounds: raw-archive input only, one small model call, never digest-of-digest.
const (
	digestFile      = "digest.md"
	digestMaxInput  = 40 << 10
	digestMaxLines  = 40
	digestTimeout   = 3 * time.Minute
	digestModel     = "haiku"
	digestPromptFmt = "Summarize these archived memory entries (decisions, session summaries, conventions) into at most %d " +
		"markdown bullet lines of durable facts. Keep dates and any [id] tags. Output only the bullets.\n\n%s"
)

// archiveFiles lists dir's raw archive .md files, sorted; ReadDir (not Glob) so bracket chars in dir stay literal.
func archiveFiles(dir string) ([]string, error) {
	ents, err := os.ReadDir(archiveDir(dir))
	if err != nil && !os.IsNotExist(err) {
		return nil, err
	}
	var files []string
	for _, e := range ents {
		if strings.HasSuffix(e.Name(), ".md") && e.Name() != digestFile {
			files = append(files, filepath.Join(archiveDir(dir), e.Name()))
		}
	}
	return files, nil
}

// digestInput is dir's raw archive (every archive/*.md except the digest itself), oldest file first, and its sources.
func digestInput(dir string) (string, []string, error) {
	files, err := archiveFiles(dir)
	if err != nil {
		return "", nil, err
	}
	var b strings.Builder
	var used []string
	var total int64
	for _, f := range files {
		fi, err := os.Stat(f)
		if err != nil {
			return "", nil, err
		}
		if total += fi.Size(); total > digestMaxInput { // bound before reading the rest
			return "", used, fmt.Errorf("needs-scope: raw archive is over the %d KB digest cap; archive less or digest by hand", digestMaxInput>>10)
		}
		data, err := os.ReadFile(f)
		if err != nil {
			return "", nil, err
		}
		fmt.Fprintf(&b, "\n<!-- %s -->\n%s\n", filepath.Base(f), data)
		used = append(used, filepath.Base(f))
	}
	if b.Len() > digestMaxInput {
		return "", used, fmt.Errorf("needs-scope: raw archive is %d KB, over the %d KB digest cap; archive less or digest by hand", b.Len()>>10, digestMaxInput>>10)
	}
	return b.String(), used, nil
}

// headlessClaudeEnv marks an update child; a stored setup-token keeps it working after the interactive /login expires.
func headlessClaudeEnv() []string {
	env := append(os.Environ(), UpdateChildEnv+"=1")
	if os.Getenv(providers.OAuthTokenEnv) == "" {
		if tok := providers.HeadlessOAuthToken(); tok != "" {
			env = append(env, providers.OAuthTokenEnv+"="+tok)
		}
	}
	return env
}

// runDigestModel runs one bounded, tool-less headless call over input and returns its capped, non-empty output lines.
func runDigestModel(ctx context.Context, dir, claude, input string) ([]string, error) {
	ctx, cancel := context.WithTimeout(ctx, digestTimeout)
	defer cancel()
	cmd := exec.CommandContext(ctx, claude, "-p", fmt.Sprintf(digestPromptFmt, digestMaxLines, input), "--model", digestModel, "--max-turns", "1",
		"--tools", "", "--setting-sources", "") // untrusted archive text: no tools, no user settings
	cmd.Dir = dir
	proc.OwnGroup(cmd)              // the timeout kills the call's whole group, not just claude
	cmd.WaitDelay = 5 * time.Second // a grandchild holding the pipe must not outlive the timeout
	cmd.Env = headlessClaudeEnv()
	var out, errb bytes.Buffer
	cmd.Stdout, cmd.Stderr = &out, &errb
	if err := cmd.Run(); err != nil {
		return nil, fmt.Errorf("digest model call: %v: %s", err, strings.TrimSpace(errb.String()))
	}
	lines := strings.Split(strings.TrimSpace(out.String()), "\n")
	if len(lines) > digestMaxLines {
		lines = lines[:digestMaxLines]
	}
	if strings.TrimSpace(lines[0]) == "" {
		return nil, errors.New("digest model returned nothing")
	}
	return lines, nil
}

// Digest summarizes dir's archive into archive/digest.md with one headless call outside the lock; failure keeps it.
func Digest(ctx context.Context, dir, claude string) (string, error) {
	if claude == "" {
		return "", errors.New("claude binary not found")
	}
	input, used, err := digestInput(dir)
	if err != nil || len(used) == 0 {
		if err == nil {
			err = fmt.Errorf("no raw archive under %s", archiveDir(dir))
		}
		return "", err
	}
	lines, err := runDigestModel(ctx, dir, claude, input)
	if err != nil {
		return "", err
	}
	body := "# Archive digest\n\n> GENERATED by `claude-code memory digest` (" + time.Now().Format("2006-01-02") +
		") from the raw archive: " + strings.Join(used, ", ") + ". Raw files stay the source of truth.\n\n" + strings.Join(lines, "\n") + "\n"
	path := filepath.Join(archiveDir(dir), digestFile)
	err = WithBankLock(BankLockWait, func() error {
		snap, err := snapshotFile(path)
		if err != nil {
			return err
		}
		if err := paths.AtomicWrite(path, []byte(body), 0o600); err != nil {
			return err
		}
		cerr := commitStore("digest: "+filepath.Base(dir), storeRels([]string{path})...)
		if cerr == nil {
			return nil
		}
		return errors.Join(cerr, snap.restore())
	})
	return path, err
}
