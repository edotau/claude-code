// catalogHomeMax bounds the home entry lines the catalog carries; the rest are reachable by search.
const catalogHomeMax = 10

// buildBankRegion renders dir's generated MEMORY.md region: one pointer per typed file, then the newest entries.
func buildBankRegion(dir string, now time.Time) string {
	head := []string{bankRegionBegin + " generated by claude-code memory index " + now.Format("2006-01-02") + " -->",
		"Bank (typed files; read on demand, `claude-code memory search` finds entries):"}
	for _, name := range bankFiles {
		if _, err := os.Stat(filepath.Join(dir, name)); err == nil {
			head = append(head, fmt.Sprintf("- [%s](%s) — %s", strings.TrimSuffix(name, ".md"), name, bankDescriptions[name]))
		}
	}
	var entries []string
	for _, s := range []struct{ file, prefix string }{{"decisionLog.md", "## "}, {"sessionHistory.md", "## "}} {
		for _, e := range entriesWithPrefix(filepath.Join(dir, s.file), s.prefix) {
			entries = append(entries, "- "+strings.TrimSuffix(s.file, ".md")+": "+e)
		}
	}
	lines := head
	room := BankRegionMaxLines - len(head) - 2 // the end marker plus a possible "more" line
	for i, e := range entries {
		if i >= room || len(strings.Join(lines, "\n"))+len(e) > BankRegionMaxBytes-200 {
			lines = append(lines, fmt.Sprintf("- … %d more entries (memory search)", len(entries)-i))
			break
		}
		lines = append(lines, e)
	}
	return strings.Join(append(lines, bankRegionEnd), "\n") + "\n"
}

// bankDescriptions are the pointer hooks for the six typed files.
var bankDescriptions = map[string]string{
	"projectContext.md": "orientation",
	"activeContext.md":  "current focus, open questions, next steps",
	"progress.md":       "what works, in progress, known issues",
	"decisionLog.md":    "dated decisions (supersede, never delete)",
	"conventions.md":    "learned working rules",
	"sessionHistory.md": "newest-first session summaries",
}

// writeBankRegion replaces (or inserts at the top) dir's MEMORY.md region; bytes outside it never change.
func writeBankRegion(dir string, now time.Time) (bool, error) {
	path := filepath.Join(dir, NativeIndexFile)
	raw, err := os.ReadFile(path)
	if err != nil && !os.IsNotExist(err) {
		return false, err
	}
	text := string(raw)
	if err := checkBankRegionMarkers(text); err != nil {
		return false, fmt.Errorf("%s: %w", path, err)
	}
	region := buildBankRegion(dir, now)
	var next string
	if start, end := bankRegionBounds(text); start >= 0 {
		next = text[:start] + region + text[end:]
	} else {
		next = region + text
	}
	if next == text {
		return false, nil
	}
	return true, paths.AtomicWrite(path, []byte(next), 0o644)
}

// checkBankRegionMarkers rejects a malformed region (a diagnostic, never a guess); size is ours to regenerate.
func checkBankRegionMarkers(text string) error {
	_, _, err := scanBankRegion(text)
	return err
}

// BuildCatalog renders the store-root router: every repo store with its hook and freshness, then home entries.
func BuildCatalog(now time.Time) (string, error) {
	entries, err := RepoDirs()
	if err != nil {
		return "", err
	}
	var b strings.Builder
	b.WriteString("# Memory catalog\n\n> GENERATED by `claude-code memory index` (" + now.Format("2006-01-02") +
		") — do not hand-edit. Start here: pick the repo(s), open `<repo>/MEMORY.md`, load only what you need.\n\n## Repos\n\n")
	for _, e := range entries {
		last := newestMarkdown(e.Dir)
		when := "never"
		if !last.IsZero() {
			when = last.Format("2006-01-02")
		}
		fmt.Fprintf(&b, "- %s — %s · last %s → %s/MEMORY.md%s\n", e.Key, storeHook(e), when, e.Key, catalogOriginComment(e.Origin))
	}
	var rows []string
	// collectKnowledge lists dir's own knowledge/*.md.
	collectKnowledge := func(label, dir string) {
		m, _ := filepath.Glob(filepath.Join(KnowledgeDir(dir), "*.md"))
		for _, f := range m {
			if filepath.Base(f) == "README.md" {
				continue
			}
			rows = append(rows, "- "+label+"/knowledge/"+filepath.Base(f)+" — "+storeHookFile(f))
		}
	}
	collectKnowledge("home", HomeBankDir())
	for _, e := range entries {
		collectKnowledge(e.Key, e.Dir)
	}
	if len(rows) > 0 {
		b.WriteString("\n## Knowledge (local, memory/<bank>/knowledge/)\n\n" + strings.Join(rows, "\n") + "\n")
	}
	homeIdx := BuildBankIndex(HomeBankDir(), now)
	if homeIdx != "" {
		lines := strings.Split(strings.TrimSpace(homeIdx), "\n")
		var keep []string
		for _, l := range lines {
			if strings.HasPrefix(l, "- ") || strings.HasPrefix(l, "## ") {
				keep = append(keep, l)
			}
		}
		b.WriteString("\n## Home (memory/home/)\n\n")
		for i, l := range keep {
			if i >= catalogHomeMax {
				fmt.Fprintf(&b, "- … %d more (memory search)\n", len(keep)-i)
				break
			}
			b.WriteString(l + "\n")
		}
	}
	return b.String(), nil
}

// storeHook is a store's one-line routing description: projectContext's first prose line, else its origin.
func storeHook(e RepoEntry) string {
	if data, err := os.ReadFile(filepath.Join(e.Dir, "projectContext.md")); err == nil {
		for l := range strings.SplitSeq(stripFrontmatter(string(data)), "\n") {
			l = strings.TrimSpace(l)
			if l == "" || strings.HasPrefix(l, "#") || strings.HasPrefix(l, ">") || strings.HasPrefix(l, "(") {
				continue
			}
			return textutil.Truncate(l, 100)
		}
	}
	if e.Origin.Origin != "" {
		return e.Origin.Origin
	}
	return e.Key
}

// stripFrontmatter drops a leading --- … --- block; the closing fence must start its own line, so a
// block-scalar value that merely contains the literal bytes "---" can't be mistaken for it.
func stripFrontmatter(s string) string {
	_, content := markdown.StripFrontMatter([]byte(s))
	return string(content)
}

// settleUnified is SettleBank: rotate + archive in scope, regenerate region and catalog, commit.
func settleUnified(root string, now time.Time) (BankSettlement, error) {
	var s BankSettlement
	err := WithBankLock(BankLockWait, func() error {
		var dirs []string
		own := Dir(root)
		if _, err := os.Stat(own); err == nil { // an unscaffolded repo gets its store from Init (with its origin), never here
			dirs = append(dirs, own)
		}
		if g := HomeBankDir(); len(dirs) == 0 || !paths.SamePath(dirs[0], g) {
			dirs = append(dirs, g)
		}
		for _, d := range dirs {
			if err := settleDir(d, now, &s); err != nil {
				return err
			}
		}
		if err := writeCatalog(now); err != nil {
			return err
		}
		s.Indexed = true
		return commitStore("settle: " + filepath.Base(dirs[0]))
	})
	return s, err
}

// settleDir stamps block IDs, rotates sessionHistory, regenerates dir's MEMORY.md region and wraps its files.
func settleDir(d string, now time.Time, s *BankSettlement) error {
	if _, err := assignIDs(d, now); err != nil {
		return err
	}
	n, err := RotateSessionHistory(d, now)
	s.Rotated += n
	if err != nil {
		return err
	}
	if _, err = writeBankRegion(d, now); err != nil {
		return err
	}
	_, err = formatFiles(dirFmtTargets(d), false) // update writes land wrapped, so lint-docs stays clean
	return err
}

func writeCatalog(now time.Time) error {
	c, err := BuildCatalog(now)
	if err != nil {
		return err
	}
	return paths.AtomicWrite(filepath.Join(StoreDir(), CatalogFile), []byte(c), 0o644)
}

// commitStore commits every dirty path in the store (update writes + settle output) as one settle commit.
func commitStore(subject string) error {
	repo := StoreRepo()
	if !repo.Exists() {
		return nil
	}
	st, err := repo.Status()
	if err != nil {
		return err
	}
	var rels []string
	for _, e := range st {
		rels = append(rels, e.Path)
	}
	if len(rels) == 0 {
		return nil
	}
	_, _, err = repo.Commit(rels, subject, "")
	return err
}

// newestMarkdown is the newest mtime across dir's top-level .md files (typed files and native topics alike).
func newestMarkdown(dir string) time.Time {
	var newest time.Time
	ents, _ := os.ReadDir(dir)
	for _, e := range ents {
		if e.IsDir() || !strings.HasSuffix(e.Name(), ".md") {
			continue
		}
		if fi, err := e.Info(); err == nil && fi.ModTime().After(newest) {
			newest = fi.ModTime()
		}
	}
	return newest
}

// knowledgeFiles are the home bank's knowledge/*.md (cross-repo) plus root's own bank knowledge/*.md
// (repo-specific); README.md is the tier's own doc.
func knowledgeFiles(root string) []string {
	dirs := []string{KnowledgeDir(HomeBankDir())}
	if !IsHomeBank(root) {
		dirs = append(dirs, KnowledgeDir(Dir(root)))
	}
	var out []string
	for _, d := range dirs {
		m, _ := filepath.Glob(filepath.Join(d, "*.md"))
		for _, f := range m {
			if filepath.Base(f) != "README.md" {
				out = append(out, f)
			}
		}
	}
	return out
}

// storeHookFile is a knowledge note's first prose line (its routing hook).
func storeHookFile(path string) string {
	data, err := os.ReadFile(path)
	if err != nil {
		return filepath.Base(path)
	}
	for l := range strings.SplitSeq(stripFrontmatter(string(data)), "\n") {
		if l = strings.TrimSpace(l); l != "" && !strings.HasPrefix(l, "#") {
			return textutil.Truncate(l, 100)
		}
	}
	return filepath.Base(path)
}
