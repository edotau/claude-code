// BankIndexFile is the generated routing index inside a bank dir — never hand-edit.
const BankIndexFile = "index.md"

// BuildBankIndex renders one routing line per durable entry (two-stage recall); "" when nothing is indexable.
func BuildBankIndex(dir string, now time.Time) string {
	var b strings.Builder
	total := 0
	section := func(name, prefix, unit string) {
		entries := entriesWithPrefix(filepath.Join(dir, name), prefix)
		if len(entries) == 0 {
			return
		}
		total += len(entries)
		fmt.Fprintf(&b, "\n## %s (%d %s)\n\n", name, len(entries), unit)
		for _, e := range entries {
			b.WriteString("- " + e + "\n")
		}
	}
	section("decisionLog.md", "## ", "entries")
	section("sessionHistory.md", "## ", "entries")
	section("conventions.md", "- ", "items")
	if total == 0 {
		return ""
	}
	return "# Memory Bank Index\n\n" +
		"> GENERATED by `claude-code memory index` (" + now.Format("2006-01-02") + ") — do not hand-edit.\n" +
		"> Route, then read: scan these lines, open only the entry you need in the named file.\n" + b.String()
}

// WriteBankIndex regenerates <dir>/index.md; returns its path ("" when the bank has nothing to index).
func WriteBankIndex(dir string, now time.Time) (string, error) {
	content := BuildBankIndex(dir, now)
	if content == "" {
		return "", nil
	}
	path := filepath.Join(dir, BankIndexFile)
	return path, paths.AtomicWrite(path, []byte(content), 0o644)
}

// RotateSessionHistory moves entries past the cap to <dir>/archive/sessionHistory-<yyyy-mm>.md, archive first.
func RotateSessionHistory(dir string, now time.Time) (int, error) {
	path := filepath.Join(dir, "sessionHistory.md")
	data, err := os.ReadFile(path)
	if err != nil {
		return 0, nil
	}
	header, entries := splitHeadingBlocks(string(data))
	if len(entries) <= SessionHistoryMaxEntries {
		return 0, nil
	}
	keep, overflow := entries[:SessionHistoryMaxEntries], entries[SessionHistoryMaxEntries:]
	archive := filepath.Join(dir, "archive", "sessionHistory-"+now.Format("2006-01")+".md")
	if err := appendBlocks(archive, overflow); err != nil {
		return 0, err // never truncate unarchived entries
	}
	if err := paths.AtomicWrite(path, []byte(rejoin(header, keep)), 0o600); err != nil {
		return 0, err
	}
	return len(overflow), nil
}

// lockPath serializes bank writers (the harvest worker's headless pass, then its settle); the
// physical lock lives under state, namespaced per store key — never beside the committed bank.
func lockPath(dir string) string { return filepath.Join(storeLockDir(dir), ".postharvest") }

// BankSettlement counts what one settle pass moved — rotation, promotion, archiving, and whether
// the index was refreshed. A single "moved" number would hide rotation and index refreshes entirely.
type BankSettlement struct {
	Rotated  int  // sessionHistory entries moved to <bank>/archive/sessionHistory-<yyyy-mm>.md
	Promoted int  // blocks moved local → global, deduped
	Archived int  // blocks moved to <bank>/archive — the relief valve when local IS global
	Indexed  bool // the routing index was rewritten
}

// Moved is the promote+archive total.
func (s BankSettlement) Moved() int { return s.Promoted + s.Archived }

// Any reports whether the pass changed anything at all.
func (s BankSettlement) Any() bool { return s.Moved() > 0 || s.Rotated > 0 }

// SettleBank rotates root's sessionHistory, promotes/archives settled overflow, and refreshes the
// local (and global) index — all under the bank lock. Deletes nothing.
func SettleBank(root string, now time.Time) (BankSettlement, error) {
	if CutOver() { // overflow archives in scope; no auto-promotion to global
		return settleUnified(root, now)
	}
	dir := Dir(root)
	var s BankSettlement
	err := paths.WithFileLock(lockPath(dir), func() error {
		cleanupLegacyLocks(dir) // one-time: old dotfile locks left beside the bank from before the move
		n, rerr := RotateSessionHistory(dir, now)
		s.Rotated = n
		if rerr != nil {
			return rerr
		}
		p, perr := PromoteLocalToGlobal(root, now)
		s.Promoted = p
		if perr != nil {
			return perr
		}
		a, aerr := ArchiveSettledOverflow(root, now)
		s.Archived += a
		if aerr != nil {
			return aerr
		}
		_, ierr := WriteBankIndex(dir, now)
		s.Indexed = ierr == nil
		return ierr
	})
	if !IsGlobal(root) {
		// Promotion appends to the global tier from every project, so its settled overflow must
		// archive from everywhere too, or the global bank grows unbounded.
		if a, _ := ArchiveSettledOverflow(GlobalDir(), now); a > 0 {
			s.Archived += a
		}
		if _, gerr := WriteBankIndex(GlobalDir(), now); err == nil {
			err = gerr
		}
	}
	return s, err
}

// NewestMtime is the newest mtime across dir's six typed files — the "did the harvest write?" probe.
func NewestMtime(dir string) time.Time {
	var newest time.Time
	for _, name := range bankFiles {
		if fi, err := os.Stat(filepath.Join(dir, name)); err == nil && fi.ModTime().After(newest) {
			newest = fi.ModTime()
		}
	}
	return newest
}
