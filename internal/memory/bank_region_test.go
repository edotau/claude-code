// Readers collapse a malformed region to absent; the scanner every rewrite gates on must tell them apart.
func TestScanBankRegionDistinguishesAbsentFromMalformed(t *testing.T) {
	t.Parallel()
	if _, _, err := scanBankRegion("plain\n"); err != nil {
		t.Errorf("absent region: err = %v, want nil", err)
	}
	for name, text := range map[string]string{
		"begin only":       "<!-- bank:begin x -->\nno end\n",
		"end only":         "stray\n<!-- bank:end -->\n",
		"two regions":      bankRegionFixture + bankRegionFixture,
		"end before begin": "<!-- bank:end -->\n<!-- bank:begin x -->\n",
	} {
		_, _, err := scanBankRegion(text)
		if !errors.Is(err, errBankRegion) {
			t.Errorf("%s: err = %v, want errBankRegion", name, err)
		}
	}
}

// TestBuildBankRegionKeepsFiveIDedEntriesAndOnePointer: 12 entries leave 5 with ids, a count of the rest, one pointer.
func TestBuildBankRegionKeepsFiveIDedEntriesAndOnePointer(t *testing.T) {
	t.Parallel()
	dir := t.TempDir()
	for _, name := range bankFiles {
		write(t, filepath.Join(dir, name), "# "+name+"\n")
	}
	const total = 12
	var b strings.Builder
	for i := 1; i <= total; i++ {
		fmt.Fprintf(&b, "## 2026-02-%02d — decision %d <!-- id:%08x -->\n\n", i, i, i)
	}
	write(t, filepath.Join(dir, "decisionLog.md"), b.String())

	region, err := buildRegionFrom(func(name string) string { return filepath.Join(dir, name) }, time.Date(2026, 1, 1, 0, 0, 0, 0, time.UTC))
	if err != nil {
		t.Fatal(err)
	}
	if n := strings.Count(region, "\n- decisionLog: "); n != bankRegionMaxEntries {
		t.Errorf("%d entry lines, want %d:\n%s", n, bankRegionMaxEntries, region)
	}
	for i := 1; i <= bankRegionMaxEntries; i++ {
		if id := fmt.Sprintf("[%08x]", i); !strings.Contains(region, id) {
			t.Errorf("entry %d lost its %s:\n%s", i, id, region)
		}
	}
	if want := fmt.Sprintf("… %d more entries (memory search)", total-bankRegionMaxEntries); !strings.Contains(region, want) {
		t.Errorf("region missing %q:\n%s", want, region)
	}
	names := make([]string, len(bankFiles))
	for i, f := range bankFiles {
		names[i] = strings.TrimSuffix(f, ".md")
	}
	pointer := "\nBank: " + strings.Join(names, ", ") + " (.md)"
	if got := [2]int{strings.Count(region, "Bank: "), strings.Count(region, pointer)}; got != [2]int{1, 1} {
		t.Errorf("want one pointer listing %v in order:\n%s", names, region)
	}
}

func TestKnowledgeNotesAndCatalogByLayout(t *testing.T) {
	eachLayoutRoot(t, func(t *testing.T, root string) {
		if _, err := Init(root); err != nil {
			t.Fatal(err)
		}
		b := BankFor(root)
		write(t, b.Sub("knowledge", "mine.md"), "# T\n\nown note hook\n")
		write(t, Bank{Key: "other"}.Sub("knowledge", "theirs.md"), "# T\n\nforeign\n")
		write(t, HomeBank().Sub("knowledge", "shared.md"), "# T\n\nhome hook\n")
		got := knowledgeFiles(root)
		var names []string
		for _, f := range got {
			names = append(names, filepath.Base(f))
		}
		if len(got) != 2 || strings.Contains(strings.Join(names, " "), "theirs") {
			t.Errorf("knowledgeFiles = %v, want the root bank's and home's notes only", names)
		}
		cat, err := BuildCatalog(time.Now())
		if err != nil {
			t.Fatal(err)
		}
		if want := "→ " + catalogPointer(b); !strings.Contains(cat, want) {
			t.Errorf("catalog lacks %q:\n%s", want, cat)
		}
		if storeFlat() && !strings.Contains(cat, "proj--projectContext.md") {
			t.Errorf("flat catalog must point at <key>--projectContext.md:\n%s", cat)
		}
		row := b.Key + "/knowledge/mine.md"
		if storeFlat() {
			row = "knowledge/" + b.Prefix() + "mine.md"
		}
		if !strings.Contains(cat, "- "+row+" — ") {
			t.Errorf("catalog lacks knowledge row %q:\n%s", row, cat)
		}
	})
}
