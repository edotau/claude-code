// assertPointers checks region links every present typed file and none of the absent ones.
func assertPointers(t *testing.T, region string, present, absent []string) {
	t.Helper()
	for _, p := range present {
		if !strings.Contains(region, p) {
			t.Errorf("region missing present-file pointer %q:\n%s", p, region)
		}
	}
	for _, a := range absent {
		if strings.Contains(region, a) {
			t.Errorf("region pointed at an absent typed file %q:\n%s", a, region)
		}
	}
}

func TestBuildBankRegionCapsAndPresentPointersOnly(t *testing.T) {
	t.Parallel()
	dir := t.TempDir()
	write(t, filepath.Join(dir, "activeContext.md"), "# Active\n")
	write(t, filepath.Join(dir, "progress.md"), "# Progress\n")
	var b strings.Builder
	for i := 1; i <= 50; i++ {
		fmt.Fprintf(&b, "## 2026-01-%02d — decision %d\n\nwhy: because\n\n", i%28+1, i)
	}
	write(t, filepath.Join(dir, "decisionLog.md"), b.String())

	now := time.Date(2026, 1, 1, 0, 0, 0, 0, time.UTC)
	region, err := buildRegionFrom(func(name string) string { return filepath.Join(dir, name) }, now)
	if err != nil {
		t.Fatal(err)
	}

	if n := strings.Count(region, "\n"); n > bankRegionMaxLines {
		t.Errorf("region has %d lines, want <= %d:\n%s", n, bankRegionMaxLines, region)
	}
	if len(region) >= bankRegionMaxBytes {
		t.Errorf("region is %d bytes, want < %d", len(region), bankRegionMaxBytes)
	}
	assertPointers(t, region, []string{"Bank: activeContext, progress, decisionLog (.md)"},
		[]string{"projectContext", "conventions", "sessionHistory"})
	if !strings.Contains(region, "more entries (memory search)") {
		t.Errorf("region missing the overflow marker for 50 decisions:\n%s", region)
	}
	if !strings.HasPrefix(region, bankRegionBegin) || !strings.Contains(region, bankRegionEnd) {
		t.Errorf("region missing its markers:\n%s", region)
	}
}

func TestWriteBankRegionInsertsReplacesAndRefuses(t *testing.T) {
	eachLayout(t, func(t *testing.T, b Bank) {
		now := time.Date(2026, 1, 1, 0, 0, 0, 0, time.UTC)
		index := b.NativeIndex()

		changed, err := writeBankRegion(b, now)
		if err != nil || !changed {
			t.Fatalf("insert into an absent file: changed=%v err=%v", changed, err)
		}
		first := mustRead(t, index)
		if !strings.HasPrefix(first, bankRegionBegin) {
			t.Fatalf("region not inserted at the top:\n%s", first)
		}

		write(t, index, first+"hand-written trailing notes\n")
		changed, err = writeBankRegion(b, now.Add(24*time.Hour))
		if err != nil {
			t.Fatal(err)
		}
		if !changed {
			t.Error("a date-bumped region must report changed")
		}
		second := mustRead(t, index)
		if !strings.HasSuffix(second, "hand-written trailing notes\n") {
			t.Errorf("bytes outside the region changed:\n%s", second)
		}

		if changed, err = writeBankRegion(b, now.Add(24*time.Hour)); err != nil || changed {
			t.Errorf("an identical rewrite must report no change: changed=%v err=%v", changed, err)
		}

		assertDoubledMarkerRefused(t, b, second, now)
	})
}

// assertDoubledMarkerRefused appends a second begin marker to base and requires the rewrite to refuse, bytes intact.
func assertDoubledMarkerRefused(t *testing.T, b Bank, base string, now time.Time) {
	t.Helper()
	broken := base + bankRegionBegin + " generated by claude-code memory index 2026-01-01 -->\nextra\n"
	write(t, b.NativeIndex(), broken)
	if _, err := writeBankRegion(b, now); !errors.Is(err, errBankRegion) {
		t.Errorf("writeBankRegion on a doubled-marker file err = %v, want errBankRegion", err)
	}
	if got := mustRead(t, b.NativeIndex()); got != broken {
		t.Error("a refused rewrite must leave every byte in place")
	}
}

