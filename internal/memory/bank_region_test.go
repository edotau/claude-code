// countPrefixed counts the lines of s that start with prefix.
func countPrefixed(s, prefix string) int {
	n := 0
	for l := range strings.SplitSeq(s, "\n") {
		if strings.HasPrefix(l, prefix) {
			n++
		}
	}
	return n
}

