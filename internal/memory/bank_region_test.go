func TestBankRegionBoundsSingle(t *testing.T) {
	t.Parallel()
	start, end := bankRegionBounds(bankRegionFixture)
	if start < 0 || end < 0 || end <= start {
		t.Fatalf("bounds = (%d,%d), want a valid span", start, end)
	}
	region := bankRegionFixture[start:end]
	if !strings.HasPrefix(region, "<!-- bank:begin") || !strings.Contains(region, "<!-- bank:end -->") {
		t.Errorf("region does not span begin..end markers:\n%s", region)
	}
}

