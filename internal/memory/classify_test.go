// TestClassifyMemoryFile tables every name shape a native store dir can hold.
func TestClassifyMemoryFile(t *testing.T) {
	tempConfig(t)
	dir := t.TempDir()
	if err := os.MkdirAll(dir, 0o755); err != nil {
		t.Fatal(err)
	}
	for _, n := range bankFiles {
		write(t, filepath.Join(dir, n), "bank body\n")
	}
	for _, n := range []string{NativeIndexFile, NativeSearchableFile, NativeArchiveIndexFile, CatalogFile} {
		write(t, filepath.Join(dir, n), "reserved body\n")
	}
	write(t, filepath.Join(dir, legacyOriginFile), "{}\n") // origin now lives in the vault; the on-disk file is an unknown dotfile
	write(t, filepath.Join(dir, "notes.md"), "---\nname: notes\nharness_kind: bank\n---\n\nbody\n")
	write(t, filepath.Join(dir, "topic.md"), "---\nname: topic\n---\n\nbody\n")
	write(t, filepath.Join(dir, "real.md"), "---\nname: real\n---\n\nbody\n")
	if err := os.Symlink(filepath.Join(dir, "real.md"), filepath.Join(dir, "link.md")); err != nil {
		t.Fatal(err)
	}
	if err := os.MkdirAll(filepath.Join(dir, "subtree.md"), 0o755); err != nil {
		t.Fatal(err)
	}

	cases := map[string]FileKind{
		NativeIndexFile:        KindNativeIndex,
		NativeSearchableFile:   KindSearchable,
		NativeArchiveIndexFile: KindArchiveIndex,
		CatalogFile:            KindCatalog,
		legacyOriginFile:       KindOther,
		"notes.md":             KindBank,
		"topic.md":             KindTopic,
		"link.md":              KindOther,
		"subtree.md":           KindOther,
		"../x":                 KindOther,
		"a/b.md":               KindOther,
		"":                     KindOther,
	}
	for _, n := range bankFiles {
		cases[n] = KindBank
	}

	for name, want := range cases {
		if got := classifyMemoryFile(dir, name); got != want {
			t.Errorf("classifyMemoryFile(%q) = %v, want %v", name, got, want)
		}
	}
}

const bankRegionFixture = "before\n<!-- bank:begin generated by claude-code memory index -->\n" +
	"- [a](a.md)\n- [b](b.md)\n<!-- bank:end -->\nafter\n"

func TestBankRegionBoundsAbsent(t *testing.T) {
	if start, end := bankRegionBounds("no region here\n"); start != -1 || end != -1 {
		t.Errorf("bounds = (%d,%d), want (-1,-1)", start, end)
	}
}

func TestBankRegionBoundsSingle(t *testing.T) {
	start, end := bankRegionBounds(bankRegionFixture)
	if start < 0 || end < 0 || end <= start {
		t.Fatalf("bounds = (%d,%d), want a valid span", start, end)
	}
	region := bankRegionFixture[start:end]
	if !strings.HasPrefix(region, "<!-- bank:begin") || !strings.Contains(region, "<!-- bank:end -->") {
		t.Errorf("region does not span begin..end markers:\n%s", region)
	}
}

func TestBankRegionBoundsTrailingNewline(t *testing.T) {
	content := bankRegionFixture + "\n"
	start, end := bankRegionBounds(content)
	if start < 0 || end < 0 {
		t.Fatalf("bounds = (%d,%d), want a valid span with trailing newline", start, end)
	}
}

func TestBankRegionBoundsBeginOnly(t *testing.T) {
	content := "before\n<!-- bank:begin generated by claude-code memory index -->\nno end\n"
	if start, end := bankRegionBounds(content); start != -1 || end != -1 {
		t.Errorf("bounds = (%d,%d), want (-1,-1) for an unterminated region", start, end)
	}
}

func TestBankRegionBoundsTwoBegins(t *testing.T) {
	content := bankRegionFixture + bankRegionFixture
	if start, end := bankRegionBounds(content); start != -1 || end != -1 {
		t.Errorf("bounds = (%d,%d), want (-1,-1) for a malformed double region", start, end)
	}
}

func TestOutsideBankRegionDropsExactlyTheRegion(t *testing.T) {
	got := outsideBankRegion(bankRegionFixture)
	if strings.Contains(got, "bank:begin") || strings.Contains(got, "bank:end") || strings.Contains(got, "- [a](a.md)") {
		t.Errorf("outsideBankRegion left region bytes in:\n%s", got)
	}
	if !strings.Contains(got, "before") || !strings.Contains(got, "after") {
		t.Errorf("outsideBankRegion dropped bytes outside the region:\n%s", got)
	}
}

// TestScanBankRegionDistinguishesAbsentFromMalformed: readers collapse a malformed region to absent, but the
// scanner every rewrite gates on must tell the two apart.
func TestScanBankRegionDistinguishesAbsentFromMalformed(t *testing.T) {
	if _, _, err := scanBankRegion("plain\n"); err != nil {
		t.Errorf("absent region: err = %v, want nil", err)
	}
	for name, text := range map[string]string{
		"begin only":       "<!-- bank:begin x -->\nno end\n",
		"end only":         "stray\n<!-- bank:end -->\n",
		"two regions":      bankRegionFixture + bankRegionFixture,
		"end before begin": "<!-- bank:end -->\n<!-- bank:begin x -->\n",
	} {
		_, _, err := scanBankRegion(text)
		if !errors.Is(err, errBankRegion) {
			t.Errorf("%s: err = %v, want errBankRegion", name, err)
		}
		if _, err := bankRegionLines(text); !errors.Is(err, errBankRegion) {
			t.Errorf("%s: bankRegionLines err = %v, want errBankRegion", name, err)
		}
		if err := checkBankRegion(text); !errors.Is(err, errBankRegion) {
			t.Errorf("%s: checkBankRegion err = %v, want errBankRegion", name, err)
		}
	}
}

// TestCheckBankRegionEnforcesReserve: a well-formed region past 40 lines or 4 KB is a diagnostic, not a pass.
func TestCheckBankRegionEnforcesReserve(t *testing.T) {
	if err := checkBankRegion(bankRegionFixture); err != nil {
		t.Fatalf("small region: %v", err)
	}
	tall := "<!-- bank:begin x -->\n" + strings.Repeat("- [a](a.md)\n", BankRegionMaxLines-1) + "<!-- bank:end -->\n"
	if err := checkBankRegion(tall); !errors.Is(err, errBankRegion) {
		t.Errorf("%d-line region: err = %v, want errBankRegion", BankRegionMaxLines+1, err)
	}
	wide := "<!-- bank:begin x -->\n- " + strings.Repeat("x", BankRegionMaxBytes) + "\n<!-- bank:end -->\n"
	if err := checkBankRegion(wide); !errors.Is(err, errBankRegion) {
		t.Errorf("over-4KB region: err = %v, want errBankRegion", err)
	}
	if err := checkNativeIndexLimits(strings.Repeat("x\n", NativeIndexMaxLines+1)); err == nil {
		t.Error("checkNativeIndexLimits passed a file past the native line limit")
	}
}
