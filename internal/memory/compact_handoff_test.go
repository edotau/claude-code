// fakeKey is a credential-shaped string built at run time so no literal trips a scanner.
var fakeKey = "sk-" + "proj-" + strings.Repeat("Fk", 12)

// compactRepo is a banked git repo with a decision log, today's plan and report, in an isolated config.
func compactRepo(t *testing.T) (root string) {
	t.Helper()
	isolatedConfig(t)
	root = repoRoot(t, "proj")
	write(t, Path("decisionLog.md"), "# Decision Log\n\n## 2026-11-16 — Ship the handoff <!-- id:9c2d7e41 -->\n\nbody\n\n"+
		"## 2026-11-15 — Older ruling <!-- id:e19b50c3 -->\n\nbody\n")
	write(t, filepath.Join(paths.ConfigDir(), "plans", "2026-11-16-plan.md"), "# plan\n")
	write(t, Sub("reports", "2026-11-16-review.md"), "r\n")
	return root
}

func compactInput(root string, now time.Time, ds ...HandoffDispatch) CompactHandoff {
	return CompactHandoff{SessionID: "4f1c2a9e-1111", CWD: root, Trigger: "manual", Dispatches: ds, Now: now}
}

func writeHandoff(t *testing.T, h CompactHandoff) string {
	t.Helper()
	path, err := WriteCompactHandoff(context.Background(), h)
	if err != nil || path == "" {
		t.Fatalf("WriteCompactHandoff = %q, %v", path, err)
	}
	return mustRead(t, path)
}

func TestCompactHandoffWritesSixSections(t *testing.T) {
	root := compactRepo(t)
	now := time.Now()
	running := HandoffDispatch{ID: "r1", Agent: "claude", Model: "opus", Status: "running", Started: now.Add(-12 * time.Minute),
		Brief: "TASK ID: relay-fix\nTier: deep\nOwns: /abs/agents/codex.md\nsecret body line"}
	done := HandoffDispatch{ID: "d1", Agent: "gemini", Status: "ok", Brief: "Review the plan", Started: now.Add(-time.Hour), Done: now}
	got := writeHandoff(t, compactInput(root, now, running, done))
	for _, want := range []string{"## Session", root + ";", "trigger: manual", "## Running dispatches",
		"- relay-fix: claude · opus · 12m · Owns: /abs/agents/codex.md", "- Finished since the last compaction (1): Review the plan (ok)",
		"## Working tree", "Commits since upstream: no upstream", "## Owner rulings", "- 2026-11-16 — Ship the handoff (id 9c2d7e41)",
		"## Pointers", "plans/2026-11-16-plan.md", "- Reports today (1): 2026-11-16-review.md",
		"Generated by the PreCompact hook from session state;"} {
		if !strings.Contains(got, want) {
			t.Errorf("handoff lacks %q:\n%s", want, got)
		}
	}
	if strings.Contains(got, "secret body line") || strings.Contains(got, "Tier: deep") {
		t.Errorf("brief body leaked:\n%s", got)
	}
	for ln := range strings.SplitSeq(got, "\n") {
		if utf8.RuneCountInString(ln) > handoffWidth && strings.Contains(strings.TrimSpace(ln), " ") { // one long path cannot wrap
			t.Errorf("line over %d columns: %q", handoffWidth, ln)
		}
	}
}

func TestCompactHandoffDropsCredentialShapedBriefLines(t *testing.T) {
	root := compactRepo(t)
	write(t, Path("decisionLog.md"), "# Decision Log\n\n## 2026-11-16 — Rotate "+fakeKey+" <!-- id:aa11bb22 -->\n")
	now := time.Now()
	d := HandoffDispatch{ID: "20261116T1-claude", Agent: "claude", Status: "running", Started: now,
		Brief: "TASK ID: " + fakeKey + "\nOwns: /abs/x.go " + fakeKey}
	got := writeHandoff(t, compactInput(root, now, d))
	if strings.Contains(got, fakeKey) || strings.Contains(got, "Owns:") {
		t.Errorf("credential-shaped brief text reached the file:\n%s", got)
	}
	if !strings.Contains(got, "- 20261116T1-claude: claude") {
		t.Errorf("a dropped task id must fall back to the record id:\n%s", got)
	}
}

func TestCompactHandoffOverwritesOnlyItsOwnFile(t *testing.T) {
	root := compactRepo(t)
	now := time.Now()
	other := Sub("handoffs", now.Format("2006-01-02")+"-compact-99999999.md")
	model := Sub("handoffs", now.Format("2006-01-02")+"-topic.md")
	write(t, other, "other session")
	write(t, model, "model written")
	writeHandoff(t, compactInput(root, now))
	second := writeHandoff(t, compactInput(root, now, HandoffDispatch{ID: "x", Agent: "codex", Status: "running", Started: now}))
	if mustRead(t, other) != "other session" || mustRead(t, model) != "model written" {
		t.Fatal("a second compaction touched another session's or a model-written handoff")
	}
	if mine := sessionCompactHandoffs("4f1c2a9e-1111"); len(mine) != 1 || !strings.Contains(second, "- x: codex") {
		t.Fatalf("own files = %v, want one rewritten file", mine)
	}
}

func TestResumeNoteListsModelHandoffBeforeGenerated(t *testing.T) {
	root := compactRepo(t)
	now := time.Now()
	gen, err := WriteCompactHandoff(context.Background(), compactInput(root, now))
	if err != nil {
		t.Fatal(err)
	}
	if got := ResumeNote("compact", "4f1c2a9e-1111", root, now); got != "handoff: "+gen {
		t.Fatalf("generated only: ResumeNote = %q, want the generated handoff", got)
	}
	model := Sub("handoffs", now.Format("2006-01-02")+"-session-4f1c2a9e.md")
	peer := Sub("handoffs", now.Format("2006-01-02")+"-session-99999999.md")
	write(t, model, handoffIdentity("4f1c2a9e-1111")+"\nmodel written")
	write(t, handoffDoneMarker("4f1c2a9e-1111"), "4f1c2a9e-1111\n"+model+"\nrequest")
	write(t, peer, "another session")
	later := now.Add(time.Minute)
	if err := os.Chtimes(model, later, later); err != nil {
		t.Fatal(err)
	}
	if err := os.Chtimes(peer, later.Add(time.Minute), later.Add(time.Minute)); err != nil { // the peer's is newer
		t.Fatal(err)
	}
	want := "handoff: " + model + "; generated handoff: " + gen
	if got := ResumeNote("compact", "4f1c2a9e-1111", root, later); got != want {
		t.Fatalf("ResumeNote = %q, want %q", got, want)
	}
}

func TestCompactHandoffSkipsWithoutBankOrSession(t *testing.T) {
	isolatedConfig(t)
	for _, h := range []CompactHandoff{{SessionID: "s", CWD: t.TempDir(), Now: time.Now()}, {CWD: t.TempDir()}} {
		if path, err := WriteCompactHandoff(context.Background(), h); path != "" || err != nil {
			t.Errorf("WriteCompactHandoff(%+v) = %q, %v; want a no-op", h, path, err)
		}
	}
}

func TestBranchFacts(t *testing.T) {
	cases := []struct{ line, branch, upstream, ahead string }{
		{"## main...origin/main [ahead 3, behind 1]", "main", "origin/main", "3"},
		{"## main...origin/main", "main", "origin/main", "0"},
		{"## topic", "topic", "", "0"},
	}
	for _, c := range cases {
		if b, u, a := branchFacts(c.line); b != c.branch || u != c.upstream || a != c.ahead {
			t.Errorf("branchFacts(%q) = %q %q %q", c.line, b, u, a)
		}
	}
}
