// catalogHomeMax bounds the home entry lines the catalog carries; the rest are reachable by search.
const catalogHomeMax = 10

// buildBankRegion renders dir's generated MEMORY.md region: one pointer per typed file, then the newest entries.
func buildBankRegion(dir string, now time.Time) (string, error) {
	head := []string{bankRegionBegin + " generated by claude-code memory index " + now.Format("2006-01-02") + " -->",
		"Bank (typed files; read on demand, `claude-code memory search` finds entries):"}
	for _, name := range bankFiles {
		if _, err := os.Stat(filepath.Join(dir, name)); err == nil {
			head = append(head, fmt.Sprintf("- [%s](%s) — %s", strings.TrimSuffix(name, ".md"), name, bankDescriptions[name]))
		}
	}
	var entries []string
	for _, s := range []struct{ file, prefix string }{{"decisionLog.md", "## "}, {"sessionHistory.md", "## "}} {
		found, err := entriesWithPrefix(filepath.Join(dir, s.file), s.prefix)
		if err != nil {
			return "", err
		}
		for _, e := range found {
			entries = append(entries, "- "+strings.TrimSuffix(s.file, ".md")+": "+e)
		}
	}
	lines := head
	room := bankRegionMaxLines - len(head) - 2 // the end marker plus a possible "more" line
	for i, e := range entries {
		if i >= room || len(strings.Join(lines, "\n"))+len(e) > bankRegionMaxBytes-200 {
			lines = append(lines, fmt.Sprintf("- … %d more entries (memory search)", len(entries)-i))
			break
		}
		lines = append(lines, e)
	}
	return strings.Join(append(lines, bankRegionEnd), "\n") + "\n", nil
}

// bankDescriptions are the pointer hooks for the six typed files.
var bankDescriptions = map[string]string{
	"projectContext.md": "orientation",
	"activeContext.md":  "current focus, open questions, next steps",
	"progress.md":       "what works, in progress, known issues",
	"decisionLog.md":    "dated decisions (supersede, never delete)",
	"conventions.md":    "learned working rules",
	"sessionHistory.md": "newest-first session summaries",
}

// writeBankRegion replaces (or inserts at the top) dir's MEMORY.md region; bytes outside it never change.
func writeBankRegion(dir string, now time.Time) (bool, error) {
	path := filepath.Join(dir, nativeIndexFile)
	raw, err := os.ReadFile(path)
	if err != nil && !os.IsNotExist(err) {
		return false, err
	}
	text := string(raw)
	if _, _, err := scanBankRegion(text); err != nil { // a malformed region is a diagnostic, never a guess
		return false, fmt.Errorf("%s: %w", path, err)
	}
	region, err := buildBankRegion(dir, now)
	if err != nil {
		return false, err
	}
	var next string
	if start, end := bankRegionBounds(text); start >= 0 {
		next = text[:start] + region + text[end:]
	} else {
		next = region + text
	}
	if next == text {
		return false, nil
	}
	return true, paths.AtomicWrite(path, []byte(next), 0o644)
}

// BuildCatalog renders the store-root router: every repo store with its hook and freshness, then home entries.
func BuildCatalog(now time.Time) (string, error) {
	entries, err := RepoDirs()
	if err != nil {
		return "", err
	}
	var b strings.Builder
	fmt.Fprintf(&b, "# Memory catalog\n\n> GENERATED by `claude-code memory index` (%s) — do not hand-edit. Start here: pick the repo(s), open `<repo>/MEMORY.md`, load only what you need.\n\n## Repos\n\n", now.Format("2006-01-02"))
	for _, e := range entries {
		last, err := newestMarkdown(e.Dir)
		if err != nil {
			return "", err
		}
		when := "never"
		if !last.IsZero() {
			when = last.Format("2006-01-02")
		}
		fmt.Fprintf(&b, "- %s — %s · last %s → %s/MEMORY.md%s\n", e.Key, storeHook(e), when, e.Key, catalogOriginComment(e.Origin))
	}
	writeKnowledgeRows(&b, entries)
	if err := writeHomeRows(&b); err != nil {
		return "", err
	}
	return b.String(), nil
}

// writeKnowledgeRows lists the home and per-repo knowledge notes under their own heading.
func writeKnowledgeRows(b *strings.Builder, entries []repoEntry) {
	var rows []string
	// collectKnowledge lists dir's own knowledge/*.md.
	collectKnowledge := func(label, dir string) {
		for _, f := range knowledgeNotes(dir) {
			rows = append(rows, "- "+label+"/knowledge/"+filepath.Base(f)+" — "+storeHookFile(f))
		}
	}
	collectKnowledge("home", HomeBankDir())
	for _, e := range entries {
		collectKnowledge(e.Key, e.Dir)
	}
	if len(rows) > 0 {
		b.WriteString("\n## Knowledge (local, memory/<bank>/knowledge/)\n\n")
		b.WriteString(strings.Join(rows, "\n"))
		b.WriteString("\n")
	}
}

// writeHomeRows lists the home bank's index bullets and headings, capped at catalogHomeMax.
func writeHomeRows(b *strings.Builder) error {
	homeIdx, err := buildBankIndex(HomeBankDir())
	if err != nil || homeIdx == "" {
		return err
	}
	var keep []string
	for l := range strings.SplitSeq(strings.TrimSpace(homeIdx), "\n") {
		if strings.HasPrefix(l, "- ") || strings.HasPrefix(l, "## ") {
			keep = append(keep, l)
		}
	}
	b.WriteString("\n## Home (memory/home/)\n\n")
	for i, l := range keep {
		if i >= catalogHomeMax {
			fmt.Fprintf(b, "- … %d more (memory search)\n", len(keep)-i)
			break
		}
		b.WriteString(l)
		b.WriteString("\n")
	}
	return nil
}

// storeHook is a store's one-line routing description: projectContext's first prose line, else its origin.
func storeHook(e repoEntry) string {
	if data, err := os.ReadFile(filepath.Join(e.Dir, "projectContext.md")); err == nil {
		hook, ok := firstProseLine(stripFrontmatter(string(data)), func(l string) bool {
			return strings.HasPrefix(l, "#") || strings.HasPrefix(l, ">") || strings.HasPrefix(l, "(")
		})
		if ok {
			return hook
		}
	}
	if e.Origin.Origin != "" {
		return e.Origin.Origin
	}
	return e.Key
}

// stripFrontmatter drops a leading --- … --- block; the closing fence must start its own line, so a
// block-scalar value that merely contains the literal bytes "---" can't be mistaken for it.
func stripFrontmatter(s string) string {
	_, content := markdown.StripFrontMatter([]byte(strings.ReplaceAll(s, "\r\n", "\n")))
	return string(content)
}

// newestMarkdown is the newest mtime across dir's top-level .md files (typed files and native topics alike).
func newestMarkdown(dir string) (time.Time, error) {
	var newest time.Time
	ents, err := os.ReadDir(dir)
	if err != nil && !os.IsNotExist(err) {
		return newest, err
	}
	for _, e := range ents {
		if e.IsDir() || !strings.HasSuffix(e.Name(), ".md") {
			continue
		}
		if fi, err := e.Info(); err == nil && fi.ModTime().After(newest) {
			newest = fi.ModTime()
		}
	}
	return newest, nil
}

// knowledgeFiles are the home bank's knowledge/*.md (cross-repo) plus root's own bank knowledge/*.md
// (repo-specific); README.md is the tier's own doc.
func knowledgeFiles(root string) []string {
	dirs := []string{HomeBankDir()}
	if !isHomeBank(root) {
		dirs = append(dirs, Dir(root))
	}
	var out []string
	for _, d := range dirs {
		out = append(out, knowledgeNotes(d)...)
	}
	return out
}

// knowledgeNotes lists bank dir's knowledge/*.md, minus the tier's own README.md.
func knowledgeNotes(dir string) []string {
	m, _ := filepath.Glob(filepath.Join(knowledgeDir(dir), "*.md"))
	var out []string
	for _, f := range m {
		if filepath.Base(f) != "README.md" {
			out = append(out, f)
		}
	}
	return out
}

// firstProseLine is body's first trimmed line that is non-empty and not skipped, truncated to 100.
func firstProseLine(body string, skip func(string) bool) (string, bool) {
	for l := range strings.SplitSeq(body, "\n") {
		if l = strings.TrimSpace(l); l != "" && !skip(l) {
			return textutil.Truncate(l, 100), true
		}
	}
	return "", false
}

// storeHookFile is a knowledge note's first prose line (its routing hook).
func storeHookFile(path string) string {
	data, err := os.ReadFile(path)
	if err != nil {
		return filepath.Base(path)
	}
	if hook, ok := firstProseLine(stripFrontmatter(string(data)), func(l string) bool { return strings.HasPrefix(l, "#") }); ok {
		return hook
	}
	return filepath.Base(path)
}

// The harness-generated region of MEMORY.md: its pointer lines are never counted, struck, moved or recorded.
// The region is reserved 40 lines / 4 KB including markers.
const (
	bankRegionBegin    = "<!-- bank:begin"
	bankRegionEnd      = "<!-- bank:end -->"
	bankRegionMaxLines = 40
	bankRegionMaxBytes = 4 * 1024
)

// errBankRegion marks a MEMORY.md whose generated region cannot be located safely: a diagnostic, never a guess.
var errBankRegion = errors.New("malformed bank region")

// bankRegionBounds is scanBankRegion for read-only callers; a malformed region reads as absent here.
func bankRegionBounds(text string) (start, end int) {
	start, end, _ = scanBankRegion(text)
	return start, end
}

// scanBankRegion is the byte range [start,end) of text's generated region, trailing newline included;
// (-1,-1,nil) when absent, errBankRegion for a lone marker, several of either, or end before begin.
func scanBankRegion(text string) (start, end int, err error) {
	start, end = -1, -1
	begins, ends := 0, 0
	for off := 0; off < len(text); {
		lineEnd := len(text)
		if nl := strings.IndexByte(text[off:], '\n'); nl >= 0 {
			lineEnd = off + nl + 1
		}
		line := text[off:lineEnd]
		if strings.HasPrefix(line, bankRegionBegin) {
			begins++
			start = off
		}
		if strings.Contains(line, bankRegionEnd) {
			ends++
			end = lineEnd
		}
		off = lineEnd
	}
	return validateBankRegionBounds(start, end, begins, ends)
}

func validateBankRegionBounds(start, end, begins, ends int) (int, int, error) {
	if begins == 0 && ends == 0 {
		return -1, -1, nil
	}
	if begins != 1 || ends != 1 || end <= start {
		return -1, -1, fmt.Errorf("%w: %d begin / %d end markers, want one of each, begin first", errBankRegion, begins, ends)
	}
	return start, end, nil
}
