// catalogHomeMax bounds the home entry lines the catalog carries; the rest are reachable by search.
const catalogHomeMax = 10

func buildRegionFrom(path func(name string) string, now time.Time) (string, error) {
	var names []string
	for _, name := range bankFiles {
		if _, err := os.Stat(path(name)); err == nil {
			names = append(names, strings.TrimSuffix(name, ".md"))
		}
	}
	head := []string{bankRegionBegin + " generated by claude-code memory index " + now.Format("2006-01-02") + " -->",
		"Bank: " + strings.Join(names, ", ") + " (.md); `claude-code memory search <terms>`"}
	var entries []string
	for _, s := range []struct{ file, prefix string }{{"decisionLog.md", "## "}, {"sessionHistory.md", "## "}} {
		found, err := entriesWithPrefix(path(s.file), s.prefix)
		if err != nil {
			return "", err
		}
		for _, e := range found {
			entries = append(entries, "- "+strings.TrimSuffix(s.file, ".md")+": "+e)
		}
	}
	lines := head
	room := min(bankRegionMaxEntries, bankRegionMaxLines-len(head)-2) // the end marker plus a possible "more" line
	for i, e := range entries {
		if i >= room || len(strings.Join(lines, "\n"))+len(e) > bankRegionMaxBytes-200 {
			lines = append(lines, fmt.Sprintf("- … %d more entries (memory search)", len(entries)-i))
			break
		}
		lines = append(lines, e)
	}
	return strings.Join(append(lines, bankRegionEnd), "\n") + "\n", nil
}

// writeBankRegion replaces (or inserts at the top) b's MEMORY.md region; bytes outside it never change.
func writeBankRegion(b Bank, now time.Time) (bool, error) {
	path := b.NativeIndex()
	raw, err := os.ReadFile(path)
	if err != nil && !os.IsNotExist(err) {
		return false, err
	}
	text := string(raw)
	if _, _, err := scanBankRegion(text); err != nil { // a malformed region is a diagnostic, never a guess
		return false, fmt.Errorf("%s: %w", path, err)
	}
	region, err := buildRegionFrom(Bank{Key: harnessStoreKey()}.Path, now)
	if err != nil {
		return false, err
	}
	var next string
	if start, end := bankRegionBounds(text); start >= 0 {
		next = text[:start] + region + text[end:]
	} else {
		next = region + text
	}
	if next == text {
		return false, nil
	}
	return true, paths.AtomicWrite(path, []byte(next), 0o644)
}

// BuildCatalog renders the store-root router: every repo bank with its hook and freshness, then home entries.
func BuildCatalog(now time.Time) (string, error) {
	banks := Banks()[1:]
	var b strings.Builder
	open := "its `<repo>--projectContext.md`"
	fmt.Fprintf(&b, "# Memory catalog\n\n> GENERATED by `claude-code memory index` (%s) — do not hand-edit. Start here: pick the repo(s), open %s, load only what you need.\n\n## Repos\n\n", now.Format("2006-01-02"), open)
	for _, bk := range banks {
		last, err := newestBankMarkdown(bk)
		if err != nil {
			return "", err
		}
		when := "never"
		if !last.IsZero() {
			when = last.Format("2006-01-02")
		}
		fmt.Fprintf(&b, "- %s — %s · last %s → %s\n", bk.Key, storeHook(bk), when, catalogPointer(bk))
	}
	writeKnowledgeRows(&b, banks)
	if err := writeHomeRows(&b); err != nil {
		return "", err
	}
	return b.String(), nil
}

// catalogPointer is the store-relative file a catalog row opens: the bank's projectContext.
func catalogPointer(b Bank) string {
	rel, err := filepath.Rel(StoreDir(), b.Path("projectContext.md"))
	if err != nil {
		return b.Key
	}
	return filepath.ToSlash(rel)
}

// writeKnowledgeRows lists the home and per-repo knowledge notes under their own heading.
func writeKnowledgeRows(b *strings.Builder, banks []Bank) {
	var rows []string
	for _, bk := range append([]Bank{HomeBank()}, banks...) {
		for _, f := range knowledgeNotes(bk) {
			rows = append(rows, "- knowledge/"+filepath.Base(f)+" — "+storeHookFile(f))
		}
	}
	if len(rows) > 0 {
		b.WriteString("\n## Knowledge (local, " + "memory/knowledge/<key>--" + ")\n\n")
		b.WriteString(strings.Join(rows, "\n"))
		b.WriteString("\n")
	}
}

// writeHomeRows lists the home bank's index bullets and headings, capped at catalogHomeMax.
func writeHomeRows(b *strings.Builder) error {
	homeIdx, err := buildBankIndex(HomeBank())
	if err != nil || homeIdx == "" {
		return err
	}
	var keep []string
	for l := range strings.SplitSeq(strings.TrimSpace(homeIdx), "\n") {
		if strings.HasPrefix(l, "- ") || strings.HasPrefix(l, "## ") {
			keep = append(keep, l)
		}
	}
	b.WriteString("\n## Home (" + "unprefixed files" + ")\n\n")
	for i, l := range keep {
		if i >= catalogHomeMax {
			fmt.Fprintf(b, "- … %d more (memory search)\n", len(keep)-i)
			break
		}
		b.WriteString(l)
		b.WriteString("\n")
	}
	return nil
}

// storeHook is a store's one-line routing description: projectContext's first prose line, else its origin.
func storeHook(b Bank) string {
	if data, err := os.ReadFile(b.Path("projectContext.md")); err == nil {
		hook, ok := firstProseLine(stripFrontmatter(string(data)), func(l string) bool {
			return strings.HasPrefix(l, "#") || strings.HasPrefix(l, ">") || strings.HasPrefix(l, "(")
		})
		if ok {
			return hook
		}
	}
	return b.Key
}

// stripFrontmatter drops a leading --- block; the closing fence must start its own line so "---" in a value is safe.
func stripFrontmatter(s string) string {
	_, content := textutil.StripFrontMatter([]byte(strings.ReplaceAll(s, "\r\n", "\n")))
	return string(content)
}

// newestBankMarkdown is the newest mtime across b's top-level .md files (typed files and native topics alike).
func newestBankMarkdown(b Bank) (time.Time, error) {
	var newest time.Time
	ents, err := os.ReadDir(b.SubDir(""))
	if err != nil && !os.IsNotExist(err) {
		return newest, err
	}
	keys := BankKeys()
	for _, e := range ents {
		if e.IsDir() || !strings.HasSuffix(e.Name(), ".md") || bankOfFile(e.Name(), keys).Key != b.Key {
			continue
		}
		if fi, err := e.Info(); err == nil && fi.ModTime().After(newest) {
			newest = fi.ModTime()
		}
	}
	return newest, nil
}

// knowledgeOf is the home bank's knowledge notes plus b's own.
func knowledgeOf(b Bank) []string {
	out := knowledgeNotes(HomeBank())
	if !b.Home() {
		out = append(out, knowledgeNotes(b)...)
	}
	return out
}

// knowledgeNotes lists b's knowledge notes (flat: the <key>--*.md ones), minus the tier's own README.md.
func knowledgeNotes(b Bank) []string {
	var out []string
	keys := BankKeys()
	for _, f := range globIn(b.SubDir("knowledge"), "*.md") {
		base := filepath.Base(f)
		if strings.TrimPrefix(base, b.Prefix()) == "README.md" || bankOfFile(f, keys).Key != b.Key || (b.Home() && strings.Contains(base, "--")) {
			continue
		}
		out = append(out, f)
	}
	return out
}

// firstProseLine is body's first trimmed line that is non-empty and not skipped, truncated to 100.
func firstProseLine(body string, skip func(string) bool) (string, bool) {
	for l := range strings.SplitSeq(body, "\n") {
		if l = strings.TrimSpace(l); l != "" && !skip(l) {
			return textutil.Truncate(l, 100), true
		}
	}
	return "", false
}

// storeHookFile is a knowledge note's first prose line (its routing hook).
func storeHookFile(path string) string {
	data, err := os.ReadFile(path)
	if err != nil {
		return filepath.Base(path)
	}
	if hook, ok := firstProseLine(stripFrontmatter(string(data)), func(l string) bool { return strings.HasPrefix(l, "#") }); ok {
		return hook
	}
	return filepath.Base(path)
}

// The generated MEMORY.md region: its pointer lines are never counted or moved; reserved 20 lines / 2 KB with markers.
const (
	bankRegionBegin      = "<!-- bank:begin"
	bankRegionEnd        = "<!-- bank:end -->"
	bankRegionMaxLines   = 20
	bankRegionMaxEntries = 5
	bankRegionMaxBytes   = 2 * 1024
)

// errBankRegion marks a MEMORY.md whose generated region cannot be located safely: a diagnostic, never a guess.
var errBankRegion = errors.New("malformed bank region")

// bankRegionBounds is scanBankRegion for read-only callers; a malformed region reads as absent here.
func bankRegionBounds(text string) (start, end int) {
	start, end, _ = scanBankRegion(text)
	return start, end
}

// scanBankRegion is the [start,end) range of the generated region; (-1,-1,nil) when absent, errBankRegion if malformed.
func scanBankRegion(text string) (start, end int, err error) {
	start, end = -1, -1
	begins, ends := 0, 0
	for off := 0; off < len(text); {
		lineEnd := len(text)
		if nl := strings.IndexByte(text[off:], '\n'); nl >= 0 {
			lineEnd = off + nl + 1
		}
		line := text[off:lineEnd]
		if strings.HasPrefix(line, bankRegionBegin) {
			begins++
			start = off
		}
		if strings.Contains(line, bankRegionEnd) {
			ends++
			end = lineEnd
		}
		off = lineEnd
	}
	return validateBankRegionBounds(start, end, begins, ends)
}

func validateBankRegionBounds(start, end, begins, ends int) (int, int, error) {
	if begins == 0 && ends == 0 {
		return -1, -1, nil
	}
	if begins != 1 || ends != 1 || end <= start {
		return -1, -1, fmt.Errorf("%w: %d begin / %d end markers, want one of each, begin first", errBankRegion, begins, ends)
	}
	return start, end, nil
}
