// catalogHomeMax bounds the home entry lines the catalog carries; the rest are reachable by search.
const catalogHomeMax = 10

// The generated MEMORY.md: soft caps clip the newest list; the loader limits are hard.
const (
	bankIndexNewest   = 20
	bankIndexMaxLines = 120
	bankIndexMaxBytes = 12 * 1024
	loaderMaxLines    = 200
	loaderMaxBytes    = 25 * 1024
	bankIndexHint     = "A pointer you add here is folded into index.md at session end; older ones: `claude-code memory search`"
	bankIndexUnshown  = 10
	entryShowBytes    = 512 // a longer or taller entry stays in index.md only; MEMORY.md shows its note's built row
	entryShowLines    = 4
)

// index.md is append-only: every stored line carries recordPrefix, so none can equal the recordEnd line after it.
const (
	recordPrefix   = "    "
	recordEnd      = "<!-- end of entry -->"
	catalogHeading = "## Pointer entries (appended by claude-code memory index, never rewritten)"
)

// MEMORY.md's own text runs from blockBegin to an end line holding its hash; the aside file keeps the last moved copy.
const (
	blockBegin     = "<!-- generated by claude-code memory index: rebuilt up to the end line; add pointers below it -->"
	blockEndPrefix = "<!-- end of generated text "
	asideName      = "memory-md.prev"          // in StateDir(): the previous MEMORY.md, kept by the refresh's rename
	genName        = "memory-md.gen"           // in StateDir(): the last installed MEMORY.md, proof of which block lines are ours
	legacyAside    = ".archive-MEMORY.md.prev" // store-root names of older binaries, adopted by the next refresh
	legacyGen      = ".archive-MEMORY.md.gen"
)

func asidePath() string { return filepath.Join(StateDir(), asideName) }
func genPath() string   { return filepath.Join(StateDir(), genName) }

// renameFile is os.Rename, a var so tests can model a state folder on another volume.
var renameFile = os.Rename

// keptCopies lists the kept MEMORY.md copies a refresh reads: the current one, then an older binary's.
func keptCopies() []string { return []string{asidePath(), storePath(legacyAside)} }

// errIndexProblem marks a refresh failure that automatic settle tolerates.
var errIndexProblem = errors.New("MEMORY.md refresh")

// The section titles render emits; the newest one carries its count ("## Newest 20").
const titleBank, titlePinned, titleNewest, titleUnresolved = "Bank", "Pinned", "Newest", "Unresolved"

// indexStep runs after each refresh step ("renamed", "appended", "installed"); a seam for the interleaving tests.
var indexStep = func(string) {}

// storePath is a store-relative slash path as an absolute one.
func storePath(rel string) string { return filepath.Join(StoreDir(), filepath.FromSlash(rel)) }

// pointerRow is one native note's front matter; Go reads it and never edits the note.
type pointerRow struct {
	Rel, Name, Desc string
	Pinned, OK      bool
	Modified        time.Time
}

// line is the generated pointer: the catalog's row, used when no stored entry points at the note.
func (r pointerRow) line() string {
	return "- [" + r.Name + "](" + r.Rel + ") — " + cmp.Or(clipDesc(r.Desc), strings.TrimSuffix(filepath.Base(r.Rel), ".md"))
}

// scanRows reads the front matter of every note in dirs, folders in order and files by name.
func scanRows(dirs ...string) []pointerRow {
	var rows []pointerRow
	for _, d := range dirs {
		for _, f := range searchTopicFiles(SubDir(d)) {
			rows = append(rows, readRow(f, d))
		}
	}
	return rows
}

// readRow reads only the leading front-matter block; OK is false when it is absent, unclosed or has no name.
func readRow(path, dir string) pointerRow {
	stem := strings.TrimSuffix(filepath.Base(path), ".md")
	row := pointerRow{Rel: dir + "/" + stem + ".md", Name: stem}
	f, err := os.Open(path)
	if err != nil {
		return row
	}
	defer f.Close()
	var head strings.Builder
	sc := bufio.NewScanner(f)
	for fences := 0; sc.Scan() && fences < 2; {
		line := sc.Text()
		if strings.TrimSpace(line) == "---" {
			fences++
		} else if fences == 0 {
			return row
		}
		head.WriteString(line + "\n")
		if fences == 2 {
			fm, _ := textutil.ParseFrontmatter(head.String())
			meta, _ := fm["metadata"].(map[string]any)
			name, _ := fm["name"].(string)
			desc, _ := fm["description"].(string)
			mod, _ := meta["modified"].(string)
			row.Pinned = meta["pinned"] == true
			row.Modified, _ = time.Parse(time.RFC3339, mod)
			row.Desc, row.OK = strings.Join(strings.Fields(desc), " "), name != ""
			row.Name = cmp.Or(name, stem)
		}
	}
	return row
}

// newestFirst orders rows by metadata.modified descending, undated last, ties by path.
func newestFirst(rows []pointerRow) []pointerRow {
	out := slices.Clone(rows)
	slices.SortFunc(out, func(a, b pointerRow) int {
		return cmp.Or(b.Modified.Compare(a.Modified), strings.Compare(a.Rel, b.Rel))
	})
	return out
}

// indexReport counts one native-index refresh.
type indexReport struct {
	Folded, Unresolved   int // entries appended to index.md; stored entries whose link names no file
	Pinned, Newest, More int // rendered pointers and the unlisted remainder
	Lines, Bytes         int
	Clipped              bool // the pinned set alone is over the soft cap, so no newest pointer fits
	Left                 bool // a writer recreated MEMORY.md during the refresh; the next one folds it
	Blank                int  // blank lines at entry edges in MEMORY.md: separators, not stored
	LostPins             string
}

func (r indexReport) notable() bool {
	return r.Folded > 0 || r.Clipped || r.Left || r.Blank > 0 || r.LostPins != ""
}

func (r indexReport) String() string {
	s := fmt.Sprintf("MEMORY.md %d lines, %d bytes: %d pinned, %d newest, %d more; %d entr(ies) appended to index.md, "+
		"%d unresolved", r.Lines, r.Bytes, r.Pinned, r.Newest, r.More, r.Folded, r.Unresolved)
	if r.Clipped {
		s += fmt.Sprintf("; WARNING: pinned and shown unresolved entries alone pass %d lines / %d bytes, newest pointers dropped", bankIndexMaxLines, bankIndexMaxBytes)
	}
	if r.Left {
		s += "; MEMORY.md was recreated meanwhile and left for the next refresh"
	}
	if r.Blank > 0 {
		s += fmt.Sprintf("; %d blank line(s) at entry edges in MEMORY.md not stored (separators)", r.Blank)
	}
	if r.LostPins != "" {
		s += "; " + r.LostPins
	}
	return s
}

var (
	pointerRE = sync.OnceValue(func() *regexp.Regexp {
		return regexp.MustCompile(`^(?:(?:[-*+]|\d{1,9}[.)])[ \t]+)?\[(?:[^\[\]]|\[[^\]]*\])*\]\(([^)\s]+)\)`)
	})
	entryStartRE  = sync.OnceValue(func() *regexp.Regexp { return regexp.MustCompile(`^(?:(?:[-*+]|\d{1,9}[.)])(?:[ \t]|$)|\[)`) })
	blockEndRE    = sync.OnceValue(func() *regexp.Regexp { return regexp.MustCompile(`^<!-- end of generated text [0-9a-f]{16} -->$`) })
	regionBeginRE = sync.OnceValue(func() *regexp.Regexp {
		return regexp.MustCompile(`^<!-- bank:begin generated by claude-code memory index \d{4}-\d{2}-\d{2} -->$`)
	})
	legacyRegionRE = sync.OnceValue(func() *regexp.Regexp { // every line shape the older region writer emitted
		return regexp.MustCompile("^(Bank: .* \\(\\.md\\); `claude-code memory search <terms>`|Layout: one bank for every " +
			"workspace; .* \\(see index\\.md\\)|- (decisionLog|sessionHistory): .+|- … \\d+ more entries \\(memory search\\))$")
	})
)

// bankHead is the fixed head and bank links the renderer emits after its begin line.
func bankHead() (head, bank []string) {
	var names []string
	for _, name := range bankFiles {
		if _, err := os.Stat(Path(name)); err == nil {
			stem := strings.TrimSuffix(name, ".md")
			names, bank = append(names, stem), append(bank, "- ["+stem+"]("+name+")")
		}
	}
	return []string{"Bank: " + strings.Join(names, ", ") + " (.md); `claude-code memory search <terms>`",
		"Layout: one bank for every workspace; " + strings.Join(storeFolderNames(), "/ ") + "/ (see " + routerFile + ")", bankIndexHint}, bank
}

// blockEnd is the end line for a generated block whose inner lines are inner, each hashed without a trailing "\r".
func blockEnd(inner []string) string {
	h := sha256.New()
	for _, l := range inner {
		h.Write([]byte(strings.TrimSuffix(l, "\r") + "\n"))
	}
	sum := h.Sum(nil)
	return blockEndPrefix + hex.EncodeToString(sum[:8]) + " -->"
}

// markerForm is a line as marker checks see it: no BOM on the first line, no trailing "\r" (an editor's bytes).
func markerForm(lines []string) []string {
	norm := make([]string, len(lines))
	for i, l := range lines {
		if i == 0 {
			l = strings.TrimPrefix(l, "\ufeff")
		}
		norm[i] = strings.TrimSuffix(l, "\r")
	}
	return norm
}

// inputEntries is every entry of a MEMORY.md text not provably our output, byte-exact; blanks counts edge blank lines.
func inputEntries(data, prevGen string) (out []string, blanks int) {
	if data == "" {
		return nil, 0
	}
	lines := strings.Split(strings.TrimSuffix(data, "\n"), "\n")
	norm, run := markerForm(lines), []string(nil)
	flush := func() {
		es, n := splitEntries(run)
		out, blanks, run = append(out, es...), blanks+n, nil
	}
	for i := 0; i < len(lines); i++ {
		end := generatedEnd(norm, i)
		if end < 0 {
			run = append(run, lines[i])
			continue
		}
		flush()
		if norm[i] != blockBegin {
			run = legacyInput(lines[i+1:end], norm[i+1:end]) // the older region's own lines go; anything else is input
		} else if norm[end] != blockEnd(lines[i+1:end]) {
			run = editedInput(lines[i+1:end], norm[i+1:end], prevGen)
		}
		flush()
		i = end
	}
	flush()
	return out, blanks
}

// generatedEnd is the closing line of a generated span opening at i (ours, or the older bank region), else -1.
func generatedEnd(lines []string, i int) int {
	isEnd := blockEndRE().MatchString
	switch {
	case lines[i] == blockBegin:
	case regionBeginRE().MatchString(lines[i]):
		isEnd = func(l string) bool { return l == "<!-- bank:end -->" }
	default:
		return -1
	}
	for j := i + 1; j < len(lines); j++ {
		if isEnd(lines[j]) {
			return j
		}
	}
	return -1 // unclosed: not provably ours, so input
}

// legacyInput is the lines of an older bank:begin region that the older generator could not have written.
func legacyInput(lines, norm []string) []string {
	var out []string
	for i, l := range lines {
		if !legacyRegionRE().MatchString(norm[i]) {
			out = append(out, l)
		}
	}
	return out
}

// editedInput is what an edit added to a hash-failed block: what lies between its common head and tail with prevGen.
func editedInput(lines, norm []string, prevGen string) []string {
	prev := markerForm(strings.Split(strings.TrimSuffix(prevGen, "\n"), "\n"))
	if len(prev) < 2 || prev[0] != blockBegin || prev[len(prev)-1] != blockEnd(prev[1:len(prev)-1]) {
		return lines
	}
	prev = prev[1 : len(prev)-1]
	p := 0
	for p < len(prev) && p < len(norm) && prev[p] == norm[p] {
		p++
	}
	q := 0
	for q < len(prev)-p && q < len(norm)-p && prev[len(prev)-1-q] == norm[len(norm)-1-q] {
		q++
	}
	return lines[p : len(lines)-q]
}

// splitEntries cuts lines into entries at each column-0 list item or bare link; blank edge lines are counted, not kept.
func splitEntries(lines []string) (out []string, blanks int) {
	var cur []string
	flush := func() {
		for len(cur) > 0 && cur[len(cur)-1] == "" {
			cur, blanks = cur[:len(cur)-1], blanks+1
		}
		for len(cur) > 0 && cur[0] == "" {
			cur, blanks = cur[1:], blanks+1
		}
		if len(cur) > 0 {
			out = append(out, strings.Join(cur, "\n"))
		}
		cur = nil
	}
	for _, l := range lines {
		if entryStartRE().MatchString(strings.TrimPrefix(l, "\ufeff")) {
			flush()
		}
		cur = append(cur, l)
	}
	flush()
	return out, blanks
}

func catalogPath() string { return filepath.Join(StoreDir(), catalogFile) }

// decodeCatalog is index.md's well-formed records in order; any other text is skipped and left where it is.
func decodeCatalog(data string) []string {
	var out, cur []string
	for l := range strings.SplitSeq(data, "\n") {
		if s, ok := strings.CutPrefix(l, recordPrefix); ok {
			cur = append(cur, s)
			continue
		}
		if strings.TrimSuffix(l, "\r") == recordEnd && len(cur) > 0 {
			out = append(out, undoCRLF(cur, l != recordEnd))
		}
		cur = nil
	}
	return out
}

// undoCRLF joins a record's lines, dropping one "\r" from each when an editor converted the record and its end line.
func undoCRLF(lines []string, crlf bool) string {
	for _, l := range lines {
		crlf = crlf && strings.HasSuffix(l, "\r")
	}
	if crlf {
		lines = slices.Clone(lines)
		for i, l := range lines {
			lines[i] = l[:len(l)-1]
		}
	}
	return strings.Join(lines, "\n")
}

func encodeRecord(e string) string {
	var b strings.Builder
	for l := range strings.SplitSeq(e, "\n") {
		b.WriteString(recordPrefix + l + "\n")
	}
	return b.String() + recordEnd + "\n"
}

// readStored reads index.md once: its records in order and as a set.
func readStored() (entries []string, held map[string]bool, data []byte, err error) {
	if data, err = readIfExists(catalogPath()); err != nil {
		return nil, nil, nil, err
	}
	entries, held = decodeCatalog(string(data)), map[string]bool{}
	for _, e := range entries {
		held[e] = true
	}
	return entries, held, data, nil
}

// fresh is entries minus those held and any repeat, in order.
func fresh(entries []string, held map[string]bool) []string {
	seen, out := maps.Clone(held), []string(nil)
	for _, e := range entries {
		if !seen[e] {
			seen[e], out = true, append(out, e)
		}
	}
	return out
}

// appendToCatalog appends the entries index.md does not hold yet; the only write Go ever makes to index.md.
func appendToCatalog(entries []string) (int, error) {
	_, held, data, err := readStored()
	if err != nil {
		return 0, err
	}
	add := fresh(entries, held)
	if len(add) == 0 {
		return 0, nil
	}
	var b strings.Builder
	b.WriteString(catalogLead(string(data)))
	for _, e := range add {
		b.WriteString(encodeRecord(e))
	}
	f, err := os.OpenFile(catalogPath(), os.O_WRONLY|os.O_CREATE|os.O_APPEND, 0o644)
	if err != nil {
		return 0, err
	}
	_, werr := f.WriteString(b.String())
	return len(add), errors.Join(werr, f.Sync(), f.Close())
}

// catalogLead ends a torn last line or record and writes the heading once, so appended records decode on their own.
func catalogLead(text string) string {
	lead := ""
	if text != "" && !strings.HasSuffix(text, "\n") {
		lead = "\n"
	}
	lines := strings.Split(strings.TrimSuffix(text, "\n"), "\n")
	if strings.HasPrefix(lines[len(lines)-1], recordPrefix) {
		lead += "\n"
	}
	if !slices.Contains(lines, catalogHeading) {
		if text != "" {
			lead += "\n"
		}
		lead += catalogHeading + "\n\n"
	}
	return lead
}

// resolvePointer is the store-relative note a pointer line targets; a bare name is looked up in the note folders.
func resolvePointer(line string, byRel map[string]bool) (string, bool) {
	m := pointerRE().FindStringSubmatch(line)
	if m == nil {
		return "", false
	}
	clean := filepath.ToSlash(filepath.Clean(m[1]))
	if !filepath.IsLocal(clean) {
		return "", false
	}
	cands := []string{clean}
	if !strings.Contains(clean, "/") {
		cands = []string{}
		for _, d := range append(slices.Clone(noteDirs), "knowledge", "") {
			cands = append(cands, path.Join(d, clean))
		}
	}
	for _, c := range cands {
		if _, ok := byRel[c]; ok {
			return c, true
		}
		if fi, err := os.Stat(storePath(c)); err == nil && fi.Mode().IsRegular() {
			return c, true
		}
	}
	return "", false
}

// renderIndex is the whole MEMORY.md from index.md's entries and the notes' front matter, clipped to the bounds.
func renderIndex(rows []pointerRow, entries []string, prevGen string) (string, indexReport, error) {
	var rep indexReport
	byRel, byFile, order, unresolved := map[string]bool{}, map[string][]string{}, []string{}, []string(nil)
	for _, r := range rows {
		byRel[r.Rel] = r.Pinned
	}
	for _, e := range entries {
		rel, ok := resolvePointer(textutil.FirstLine(e), byRel)
		if !ok {
			unresolved = append(unresolved, e)
			continue
		}
		if byFile[rel] = append(byFile[rel], e); len(byFile[rel]) == 1 {
			order = append(order, rel)
		}
	}
	pinned, rest, hidden := shownRows(rows, byFile, order)
	rep.LostPins = lostPinProblem(prevGen, byRel)
	shown, unshown := shownUnresolved(unresolved)
	pins, k := len(pinned), min(bankIndexNewest, len(rest))
	build := func() string {
		return layoutIndex(pinned[:pins], rest[:k], len(pinned)-pins+len(rest)-k+hidden, shown, unshown)
	}
	over := func(t string, lines, size int) bool { return strings.Count(t, "\n") > lines || len(t) > size }
	text := build()
	for ; k > 0 && over(text, bankIndexMaxLines, bankIndexMaxBytes); text = build() {
		k--
	}
	rep.Clipped = over(text, bankIndexMaxLines, bankIndexMaxBytes)
	for ; pins > 0 && over(text, loaderMaxLines, loaderMaxBytes); text = build() {
		pins-- // newest first, so the oldest pins go
	}
	rep.Unresolved, rep.Pinned, rep.Newest, rep.More = len(unresolved), pins, k, len(pinned)-pins+len(rest)-k+hidden
	rep.Lines, rep.Bytes = strings.Count(text, "\n"), len(text)
	if pins < len(pinned) {
		return text, rep, fmt.Errorf("%w: %d pinned notes pass the loader's %d lines / %d bytes, so the %d oldest are "+
			"left out; unpin notes (metadata.pinned: true)", errIndexProblem, len(pinned), loaderMaxLines, loaderMaxBytes, len(pinned)-pins)
	}
	return text, rep, nil
}

// layoutIndex lays MEMORY.md out: the begin line, head, sections, then the end line hashing what it closes.
func layoutIndex(pinned, newest []string, more int, shown []string, unshown int) string {
	head, bank := bankHead()
	inner := slices.Concat(head, section(titleBank, bank), section(titlePinned, entryLines(pinned)),
		section(fmt.Sprintf("%s %d", titleNewest, len(newest)), entryLines(newest)))
	if more > 0 {
		inner = append(inner, fmt.Sprint("- ", more, " more: see ", routerFile, ", or `claude-code memory search <terms>`"))
	}
	tail := entryLines(shown)
	if unshown > 0 {
		tail = append(tail, fmt.Sprint("- ", unshown, " more unresolved in index.md"))
	}
	inner = append(inner, section(titleUnresolved, tail)...)
	return strings.Join(slices.Concat([]string{blockBegin}, inner, []string{blockEnd(inner)}), "\n") + "\n"
}

func entryLines(entries []string) []string {
	var out []string
	for _, e := range entries {
		out = append(out, strings.Split(e, "\n")...)
	}
	return out
}

// shownRows splits every pointed-at note, newest first, into pinned and newest display entries; hidden counts the rest.
func shownRows(rows []pointerRow, byFile map[string][]string, order []string) (pinned, rest []string, hidden int) {
	all, inRows := slices.Clone(rows), map[string]bool{}
	for _, r := range rows {
		inRows[r.Rel] = true
	}
	for _, rel := range order { // a handoff, report, knowledge or bank pointer joins the newest list
		if !inRows[rel] {
			all = append(all, folderRow(rel))
		}
	}
	for _, r := range newestFirst(all) {
		e := firstOf(byFile[r.Rel])
		if !showable(e) {
			e = ""
			if inRows[r.Rel] {
				e = r.line() // a note's built row stands in for an oversized entry
			}
		}
		switch {
		case e == "":
			hidden++
		case r.Pinned:
			pinned = append(pinned, e)
		default:
			rest = append(rest, e)
		}
	}
	return pinned, rest, hidden
}

// showable is an entry small enough to show and holding no marker line, which would end the block early on re-read.
func showable(e string) bool {
	return e != "" && len(e) <= entryShowBytes && strings.Count(e, "\n") < entryShowLines &&
		!slices.ContainsFunc(strings.Split(e, "\n"), func(l string) bool { return l == blockBegin || blockEndRE().MatchString(l) })
}

// folderRow dates a pointer target outside the note folders by its YYYY-MM-DD- name, else its front matter.
func folderRow(rel string) pointerRow {
	r := readRow(storePath(rel), path.Dir(rel))
	r.Rel = rel
	if base := path.Base(rel); len(base) >= len(time.DateOnly) {
		if d, err := time.Parse(time.DateOnly, base[:len(time.DateOnly)]); err == nil {
			r.Modified = d
		}
	}
	return r
}

// shownUnresolved is the newest bankIndexUnshown showable unresolved entries and how many index.md alone keeps.
func shownUnresolved(entries []string) (shown []string, unshown int) {
	for _, e := range slices.Backward(entries) {
		if len(shown) < bankIndexUnshown && showable(e) {
			shown = append(shown, e)
		} else {
			unshown++
		}
	}
	return shown, unshown
}

func firstOf(lines []string) string {
	if len(lines) == 0 {
		return ""
	}
	return lines[0]
}

// section is a heading plus its lines; nothing when there are none.
func section(title string, lines []string) []string {
	if len(lines) == 0 {
		return nil
	}
	return append([]string{"## " + title}, lines...)
}

// lastGenerated is the MEMORY.md text the last install wrote; unreadable means no proof, so an edit keeps every line.
func lastGenerated() string {
	data, err := os.ReadFile(genPath())
	if errors.Is(err, fs.ErrNotExist) {
		data, _ = os.ReadFile(storePath(legacyGen))
	}
	return string(data)
}

const lostPinLabel = "note(s) lost metadata.pinned:"

func lostPinProblem(prevGen string, byRel map[string]bool) string {
	_, section, ok := strings.Cut(prevGen, "\n## "+titlePinned+"\n")
	if !ok {
		return ""
	}
	var lost []string
	for line := range strings.SplitSeq(section, "\n") {
		if strings.HasPrefix(line, blockEndPrefix) || line == "## "+titleUnresolved ||
			strings.HasPrefix(line, "## "+titleNewest+" ") {
			break
		}
		if rel, ok := resolvePointer(line, byRel); ok && !pinStillSet(rel, byRel) {
			lost = append(lost, rel)
		}
	}
	if len(lost) == 0 {
		return ""
	}
	slices.Sort(lost)
	lost = slices.Compact(lost)
	return fmt.Sprintf("%d %s %s", len(lost), lostPinLabel, strings.Join(lost, ", "))
}

func pinStillSet(rel string, byRel map[string]bool) bool {
	if pinned, ok := byRel[rel]; ok {
		return pinned
	}
	return folderRow(rel).Pinned
}

// foldFile appends path's input entries, then extra, to index.md; it never writes path.
func foldFile(path string, extra []string) (int, error) {
	data, err := readIfExists(path)
	if err != nil {
		return 0, err
	}
	in, _ := inputEntries(string(data), lastGenerated())
	return appendToCatalog(append(in, extra...))
}

// planRefresh is the MEMORY.md a refresh would install, computed from reads alone.
func planRefresh(rows []pointerRow, extra []string) (string, indexReport, error) {
	if err := checkIndexFiles(); err != nil {
		return "", indexReport{}, err
	}
	entries, held, _, err := readStored()
	if err != nil {
		return "", indexReport{}, err
	}
	var in []string
	blanks := 0
	prevGen := lastGenerated()
	for _, p := range append(keptCopies(), NativeIndex()) {
		data, err := readIfExists(p)
		if err != nil {
			return "", indexReport{}, err
		}
		es, n := inputEntries(string(data), prevGen)
		in, blanks = append(in, es...), blanks+n
	}
	add := fresh(append(in, extra...), held)
	text, rep, err := renderIndex(rows, append(entries, add...), prevGen)
	rep.Folded, rep.Blank = len(add), blanks
	return text, rep, err
}

// refreshNativeIndex folds MEMORY.md into index.md by appending, then installs a new MEMORY.md without replacing one.
func refreshNativeIndex(_ time.Time, dry bool, extra []string) (indexReport, error) {
	rows := scanRows(noteDirs...)
	if _, err := os.Stat(StoreDir()); !dry && errors.Is(err, fs.ErrNotExist) {
		return finishIndexRefresh(indexReport{}, nil)
	}
	aside, n := asidePath(), 0
	if !dry {
		if err := checkIndexFiles(); err != nil {
			return indexReport{}, err
		}
		var err error
		if n, err = adoptLegacy(); err != nil {
			return indexReport{}, err
		}
		m, err := foldFile(aside, nil)
		n += m
		if err != nil { // the kept copy first: a write through an old handle lands there
			return indexReport{}, err
		}
	}
	text, rep, perr := planRefresh(rows, extra)
	mem, merr := readIfExists(NativeIndex())
	if dry || perr != nil && !errors.Is(perr, errIndexProblem) || merr != nil {
		rep.Folded += n
		return rep, errors.Join(perr, merr)
	}
	if rep.Folded == 0 && rep.LostPins == "" && string(mem) == text {
		rep.Folded += n
		return finishIndexRefresh(rep, perr)
	}
	tmp, err := stageFile(NativeIndex(), []byte(text)) // before anything moves, so a full disk fails here
	if err != nil {
		return rep, err
	}
	if err := moveAside(aside); err != nil {
		return rep, errors.Join(err, os.Remove(tmp))
	}
	indexStep("renamed")
	m, ferr := foldFile(aside, extra) // on failure the input stays in the moved file, folded by the next step 1
	indexStep("appended")
	installed, ierr := placeNoReplace(tmp, NativeIndex(), []byte(text))
	if !installed && ierr != nil {
		ierr = errors.Join(ierr, restoreMoved(aside))
	} else if installed {
		ierr = paths.AtomicWrite(genPath(), []byte(text), 0o644)
	}
	indexStep("installed")
	rep.Folded, rep.Left = n+m, !installed && ierr == nil
	return finishIndexRefresh(rep, errors.Join(ferr, ierr, perr))
}

// moveAside renames MEMORY.md to the kept copy; across volumes it refuses, nothing moved, so no text is lost.
func moveAside(aside string) error {
	if err := os.MkdirAll(filepath.Dir(aside), 0o700); err != nil {
		return err
	}
	err := renameFile(NativeIndex(), aside)
	if err != nil && !errors.Is(err, fs.ErrNotExist) {
		return fmt.Errorf("%w refused: cannot move MEMORY.md to %s (%v); the store and the state folder must be one "+
			"volume, MEMORY.md is unchanged", errIndexProblem, aside, err)
	}
	return nil
}

// adoptLegacy folds an older binary's store-root kept copy with its proof, then moves them to the state folder.
func adoptLegacy() (int, error) {
	n, err := 0, error(nil)
	if _, serr := os.Lstat(storePath(legacyAside)); serr == nil {
		if n, err = foldFile(storePath(legacyAside), nil); err != nil {
			return 0, err
		}
		if err = os.Remove(storePath(legacyAside)); err != nil {
			return n, err
		}
	}
	data, rerr := os.ReadFile(storePath(legacyGen))
	if rerr != nil {
		if errors.Is(rerr, fs.ErrNotExist) {
			rerr = nil
		}
		return n, rerr
	}
	if _, serr := os.Lstat(genPath()); errors.Is(serr, fs.ErrNotExist) {
		if err = paths.AtomicWrite(genPath(), data, 0o644); err != nil {
			return n, err
		}
	}
	return n, os.Remove(storePath(legacyGen))
}

// restoreMoved puts the moved file's bytes back as MEMORY.md when the new one could not be placed.
func restoreMoved(aside string) error {
	data, err := os.ReadFile(aside)
	if err == nil {
		_, err = installNoReplace(NativeIndex(), data)
	}
	return err
}

// checkIndexFiles refuses a symlinked, non-regular or hard-linked index file: a move or append would write elsewhere.
func checkIndexFiles() error {
	var seen []fs.FileInfo
	var names []string
	for _, n := range []string{catalogFile, nativeIndexFile, routerFile, legacyAside, legacyGen, asidePath(), genPath()} {
		if !filepath.IsAbs(n) {
			n = storePath(n)
		}
		fi, err := os.Lstat(n)
		switch {
		case errors.Is(err, fs.ErrNotExist):
			continue
		case err != nil:
			return err
		case !fi.Mode().IsRegular():
			return fmt.Errorf("%w refused: %s is a %s, not a regular file; put its text in a regular file of that name, "+
				"then run `claude-code memory index`", errIndexProblem, n, fileKind(fi.Mode()))
		}
		for i, o := range seen {
			if os.SameFile(o, fi) {
				return fmt.Errorf("%w refused: %s and %s are one file (a hard link); copy %s to a file of its own, then "+
					"run `claude-code memory index`", errIndexProblem, names[i], n, n)
			}
		}
		seen, names = append(seen, fi), append(names, n)
	}
	return nil
}

func fileKind(m fs.FileMode) string {
	switch {
	case m&fs.ModeSymlink != 0:
		return "symlink"
	case m.IsDir():
		return "directory"
	}
	return "special file"
}

// linkFile is os.Link, a var so tests can model a filesystem without hard links.
var linkFile = os.Link

// stageFile writes data to a synced temp file beside dest and returns its path.
func stageFile(dest string, data []byte) (string, error) {
	f, err := os.CreateTemp(filepath.Dir(dest), filepath.Base(dest)+".tmp-*")
	if err != nil {
		return "", err
	}
	_, werr := f.Write(data)
	if err := errors.Join(werr, f.Chmod(0o644), f.Sync(), f.Close()); err != nil {
		return "", errors.Join(err, os.Remove(f.Name()))
	}
	return f.Name(), nil
}

// placeNoReplace puts staged tmp at dest unless dest exists (false, nil): a hard link, else an exclusive create.
func placeNoReplace(tmp, dest string, data []byte) (bool, error) {
	lerr := linkFile(tmp, dest) // link(2) on Unix, CreateHardLinkW on Windows: neither replaces
	if lerr != nil && !errors.Is(lerr, fs.ErrExist) {
		lerr = createExclusive(dest, data) // no hard links here (FAT, some network mounts): O_EXCL never replaces either
	}
	rerr := os.Remove(tmp)
	if errors.Is(lerr, fs.ErrExist) {
		return false, rerr
	}
	return lerr == nil, errors.Join(lerr, rerr)
}

func createExclusive(dest string, data []byte) error {
	f, err := os.OpenFile(dest, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0o644)
	if err != nil {
		return err
	}
	_, werr := f.Write(data)
	if err := errors.Join(werr, f.Sync(), f.Close()); err != nil {
		return errors.Join(err, os.Remove(dest)) // a part-written MEMORY.md is neither the old text nor the new
	}
	return nil
}

// installNoReplace stages data and places it at dest unless dest exists (false, nil).
func installNoReplace(dest string, data []byte) (bool, error) {
	tmp, err := stageFile(dest, data)
	if err != nil {
		return false, err
	}
	return placeNoReplace(tmp, dest, data)
}

// BuildCatalog renders the store-root router: the bank's hook and freshness, its knowledge notes, then its index rows.
func BuildCatalog(now time.Time) (string, error) {
	var b strings.Builder
	fmt.Fprintf(&b, "# Memory catalog\n\n> GENERATED by `claude-code memory index` (%s) — do not hand-edit. Start here: open `projectContext.md`, load only what you need.\n\n", now.Format("2006-01-02"))
	last, err := newestBankMarkdown()
	if err != nil {
		return "", err
	}
	when := "never"
	if !last.IsZero() {
		when = last.Format("2006-01-02")
	}
	fmt.Fprintf(&b, "%s · last %s → projectContext.md\n", cmp.Or(storeHook(), "Bank"), when)
	writeLayoutRows(&b)
	writeKnowledgeRows(&b)
	if err := writeHomeRows(&b); err != nil {
		return "", err
	}
	return b.String(), nil
}

// writeKnowledgeRows lists the knowledge notes under their own heading.
func writeKnowledgeRows(b *strings.Builder) {
	var rows []string
	for _, f := range knowledgeNotes() {
		rows = append(rows, "- "+filepath.Base(f)+" — "+storeHookFile(f))
	}
	if len(rows) > 0 {
		b.WriteString("\n## Knowledge (knowledge/)\n\n")
		b.WriteString(strings.Join(rows, "\n"))
		b.WriteString("\n")
	}
}

// writeHomeRows lists the home bank's index bullets and headings, capped at catalogHomeMax.
func writeHomeRows(b *strings.Builder) error {
	homeIdx, err := buildBankIndex()
	if err != nil || homeIdx == "" {
		return err
	}
	var keep []string
	for l := range strings.SplitSeq(strings.TrimSpace(homeIdx), "\n") {
		if strings.HasPrefix(l, "- ") || strings.HasPrefix(l, "## ") {
			keep = append(keep, l)
		}
	}
	b.WriteString("\n## Index\n\n")
	for i, l := range keep {
		if i >= catalogHomeMax {
			fmt.Fprintf(b, "- … %d more (memory search)\n", len(keep)-i)
			break
		}
		b.WriteString(l)
		b.WriteString("\n")
	}
	return nil
}

// storeHook is a store's one-line routing description: projectContext's first prose line, else empty.
func storeHook() string {
	if data, err := os.ReadFile(Path("projectContext.md")); err == nil {
		hook, ok := firstProseLine(stripFrontmatter(string(data)), func(l string) bool {
			return strings.HasPrefix(l, "#") || strings.HasPrefix(l, ">") || strings.HasPrefix(l, "(")
		})
		if ok {
			return hook
		}
	}
	return ""
}

// stripFrontmatter drops a leading --- block; the closing fence must start its own line so "---" in a value is safe.
func stripFrontmatter(s string) string {
	_, content := textutil.StripFrontMatter([]byte(strings.ReplaceAll(s, "\r\n", "\n")))
	return string(content)
}

// newestBankMarkdown is the newest mtime across the store's top-level .md files (typed files and native topics alike).
func newestBankMarkdown() (time.Time, error) {
	var newest time.Time
	ents, err := os.ReadDir(SubDir(""))
	if err != nil && !os.IsNotExist(err) {
		return newest, err
	}
	for _, e := range ents {
		if e.IsDir() || !strings.HasSuffix(e.Name(), ".md") {
			continue
		}
		if fi, err := e.Info(); err == nil && fi.ModTime().After(newest) {
			newest = fi.ModTime()
		}
	}
	return newest, nil
}

// knowledgeNotes lists the knowledge--*.md notes, minus the tier's own README.md.
func knowledgeNotes() []string {
	var out []string
	for _, f := range ownedFiles("knowledge") {
		if filepath.Base(f) != "README.md" {
			out = append(out, f)
		}
	}
	return out
}

// firstProseLine is body's first trimmed line that is non-empty and not skipped, truncated to 100.
func firstProseLine(body string, skip func(string) bool) (string, bool) {
	for l := range strings.SplitSeq(body, "\n") {
		if l = strings.TrimSpace(l); l != "" && !skip(l) {
			return textutil.Truncate(l, 100), true
		}
	}
	return "", false
}

// storeHookFile is a knowledge note's first prose line (its routing hook).
func storeHookFile(path string) string {
	data, err := os.ReadFile(path)
	if err != nil {
		return filepath.Base(path)
	}
	if hook, ok := firstProseLine(stripFrontmatter(string(data)), func(l string) bool { return strings.HasPrefix(l, "#") }); ok {
		return hook
	}
	return filepath.Base(path)
}

