// Generated-handoff caps: listed lines, reports, rulings, the wrap width and the budget for every git call together.
const (
	handoffListMax    = 40
	handoffReportsMax = 20
	handoffRulingsMax = 10
	handoffWidth      = 118
	handoffGitBudget  = 250 * time.Millisecond
)

const handoffClosing = "Generated by the PreCompact hook from session state; the model-written handoff, if any, " +
	"is listed above and takes precedence where they differ."

// HandoffDispatch is one of the session's dispatches; only Brief's TASK ID and Owns lines reach the file.
type HandoffDispatch struct {
	ID, Agent, Model, Status, Brief string
	Started, Done                   time.Time // Done is zero while the job runs
}

// CompactHandoff is what PreCompact knows about the session it is compacting.
type CompactHandoff struct {
	SessionID, CWD, Trigger string
	Dispatches              []HandoffDispatch
	Now                     time.Time
}

// generatedHandoff matches the names WriteCompactHandoff writes, so they never pass for a model-written handoff.
var generatedHandoff = sync.OnceValue(func() *regexp.Regexp {
	return regexp.MustCompile(`\d{4}-\d{2}-\d{2}-compact-[A-Za-z0-9_-]{1,8}\.md$`)
})

// compactID is the session id's first 8 file-safe characters.
func compactID(sessionID string) string {
	id := paths.Slug(sessionID, "_-", 0, "session")
	return id[:min(8, len(id))]
}

// WriteCompactHandoff writes h's facts to handoffs/<date>-compact-<id8>.md; "" with no session or bank.
func WriteCompactHandoff(ctx context.Context, h CompactHandoff) (string, error) {
	if h.SessionID == "" || h.CWD == "" || !hasBank(h.CWD) {
		return "", nil
	}
	b := BankFor(h.CWD)
	since := lastCompactAt(b, h.SessionID)
	gctx, cancel := context.WithTimeout(ctx, handoffGitBudget)
	body := renderCompactHandoff(gctx, b, h, since)
	cancel()
	if err := os.MkdirAll(b.SubDir("handoffs"), 0o755); err != nil {
		return "", err
	}
	path := b.Sub("handoffs", h.Now.Format("2006-01-02")+"-compact-"+compactID(h.SessionID)+".md")
	return path, paths.AtomicWrite(path, []byte(body), 0o600)
}

// sessionCompactHandoffs are b's generated handoffs for sessionID, any date.
func sessionCompactHandoffs(b Bank, sessionID string) []string {
	files := ownedFiles(b, "handoffs")
	suffix := "-compact-" + compactID(sessionID) + ".md"
	return slices.DeleteFunc(files, func(p string) bool {
		return !strings.HasSuffix(p, suffix) || !generatedHandoff().MatchString(filepath.Base(p))
	})
}

// newestFile is the most recently modified of files within maxAge of now, or "".
func newestFile(files []string, now time.Time, maxAge time.Duration) (string, time.Time) {
	best, bestMod := "", time.Time{}
	for _, p := range files {
		fi, err := os.Stat(p)
		if err == nil && now.Sub(fi.ModTime()) <= maxAge && fi.ModTime().After(bestMod) {
			best, bestMod = p, fi.ModTime()
		}
	}
	return best, bestMod
}

// lastCompactAt is this session's previous generated handoff, else its first SessionStart, else zero.
func lastCompactAt(b Bank, sessionID string) time.Time {
	if _, at := newestFile(sessionCompactHandoffs(b, sessionID), time.Now(), 1<<62); !at.IsZero() {
		return at
	}
	if fi, err := os.Stat(sessionRootPath(sessionID)); err == nil {
		return fi.ModTime()
	}
	return time.Time{}
}

// renderCompactHandoff is the file body; any line shaped like a credential is dropped.
func renderCompactHandoff(ctx context.Context, b Bank, h CompactHandoff, since time.Time) string {
	g := readHandoffGit(ctx, h.CWD)
	sections := [][]string{
		{"# Compaction handoff: " + h.Now.Format("2006-01-02 15:04")},
		headerSection(g, h),
		dispatchSection(h.Dispatches, h.Now, since),
		treeSection(g),
		rulingsSection(b),
		pointersSection(b, h.Now),
		{handoffClosing},
	}
	var out []string
	for _, sec := range sections {
		for _, ln := range sec {
			for _, w := range wrapHandoff(ln) {
				if !textutil.CredentialRE().MatchString(w) {
					out = append(out, w)
				}
			}
		}
		out = append(out, "")
	}
	return strings.Join(out, "\n")
}

// handoffGit is the checkout's state as git reports it; truncated names the sources the budget cut.
type handoffGit struct {
	root, head, upstreamSHA string
	branchLine              string
	status, log             []string
	truncated               []string
}

// readHandoffGit runs the four git reads under ctx; a missing upstream leaves its fields empty.
func readHandoffGit(ctx context.Context, cwd string) handoffGit {
	var g handoffGit
	run := func(args ...string) string {
		out, err := proc.RunGit(ctx, "", append([]string{"-C", cwd}, args...)...)
		if err != nil && ctx.Err() != nil {
			g.truncated = append(g.truncated, args[0]+" "+args[len(args)-1])
		}
		return out
	}
	top := strings.Fields(run("rev-parse", "--show-toplevel", "--short", "HEAD"))
	if len(top) == 2 {
		g.root, g.head = top[0], top[1]
	}
	status := splitRawLines(run("status", "--short", "--branch"))
	if len(status) > 0 && strings.HasPrefix(status[0], "## ") {
		g.branchLine, status = status[0], status[1:]
	}
	g.status = status
	if g.upstreamSHA = run("rev-parse", "--short", "@{u}"); g.upstreamSHA != "" {
		g.log = splitRawLines(run("log", "--oneline", "-"+strconv.Itoa(handoffListMax+1), "@{u}..HEAD"))
	}
	return g
}

// splitRawLines splits git output into its non-empty lines, keeping status's leading columns.
func splitRawLines(out string) []string {
	return slices.DeleteFunc(strings.Split(out, "\n"), func(s string) bool { return strings.TrimSpace(s) == "" })
}

// branchFacts parses status --branch's "## main...origin/main [ahead 2, behind 1]" line.
func branchFacts(line string) (branch, upstream, ahead string) {
	rest := strings.TrimPrefix(line, "## ")
	rest, track, _ := strings.Cut(rest, " [")
	branch, upstream, _ = strings.Cut(rest, "...")
	if n, ok := strings.CutPrefix(track, "ahead "); ok {
		ahead, _, _ = strings.Cut(strings.TrimSuffix(n, "]"), ",")
	}
	return branch, upstream, cmp.Or(ahead, "0")
}

func headerSection(g handoffGit, h CompactHandoff) []string {
	branch, upstream, ahead := branchFacts(g.branchLine)
	repo := fmt.Sprintf("- Repo: %s; branch `%s`; HEAD `%s`", cmp.Or(g.root, h.CWD), cmp.Or(branch, "?"), cmp.Or(g.head, "?"))
	if g.upstreamSHA != "" {
		repo += fmt.Sprintf("; upstream `%s` at `%s`, %s ahead", upstream, g.upstreamSHA, ahead)
	} else {
		repo += "; no upstream"
	}
	sess := fmt.Sprintf("- Session: %s at %s; trigger: %s", h.SessionID, h.Now.Format("2006-01-02 15:04 MST"), cmp.Or(h.Trigger, "unknown"))
	out := []string{"## Session", repo, sess}
	if len(g.truncated) > 0 {
		out = append(out, "- truncated: git "+strings.Join(g.truncated, ", ")+" exceeded "+handoffGitBudget.String())
	}
	return out
}

// dispatchSection lists the running dispatches and those finished since the last compaction.
func dispatchSection(ds []HandoffDispatch, now, since time.Time) []string {
	out := []string{"## Running dispatches"}
	var done []string
	for _, d := range ds {
		task, owns := briefFacts(d)
		if d.Done.IsZero() {
			line := fmt.Sprintf("- %s: %s · %s · %s", task, d.Agent, cmp.Or(d.Model, "?"), age(now.Sub(d.Started)))
			if owns != "" {
				line += " · " + owns
			}
			out = append(out, line)
		} else if !d.Done.Before(since) {
			done = append(done, task+" ("+d.Status+")")
		}
	}
	if len(out) == 1 {
		out = append(out, "- none")
	}
	line := fmt.Sprintf("- Finished since the last compaction (%d)", len(done))
	if len(done) > 0 {
		shown := done[:min(len(done), 20)] // a long session finishes hundreds of probes
		line += ": " + strings.Join(shown, ", ")
		if more := len(done) - len(shown); more > 0 {
			line += fmt.Sprintf(", … %d more", more)
		}
	}
	return append(out, line)
}

// briefFacts is a dispatch's TASK ID (else brief head, else record id) and Owns: line, minus credential shapes.
func briefFacts(d HandoffDispatch) (task, owns string) {
	for ln := range strings.SplitSeq(d.Brief, "\n") {
		ln = strings.TrimSpace(ln)
		if id, ok := strings.CutPrefix(ln, "TASK ID:"); ok && task == "" {
			task = strings.TrimSpace(id)
		}
		if owns == "" && (strings.HasPrefix(ln, "Owns:") || strings.HasPrefix(ln, "Owned:")) {
			owns = textutil.CapRunes(ln, 400, "…")
		}
	}
	if task == "" {
		task = textutil.CapRunes(strings.Join(strings.Fields(d.Brief), " "), 60, "")
	}
	if textutil.CredentialRE().MatchString(task) {
		task = ""
	}
	if textutil.CredentialRE().MatchString(owns) {
		owns = ""
	}
	return cmp.Or(task, d.ID), owns
}

// age renders a duration as 45s, 12m or 1h05m.
func age(d time.Duration) string {
	switch {
	case d < time.Minute:
		return strconv.Itoa(int(d.Seconds())) + "s"
	case d < time.Hour:
		return strconv.Itoa(int(d.Minutes())) + "m"
	}
	return fmt.Sprintf("%dh%02dm", int(d.Hours()), int(d.Minutes())%60)
}

func treeSection(g handoffGit) []string {
	out := []string{"## Working tree", "Uncommitted (`git status --short`):"}
	out = append(out, fencedList(g.status)...)
	if g.upstreamSHA == "" {
		return append(out, "Commits since upstream: no upstream")
	}
	out = append(out, "Commits since upstream (`git log --oneline @{u}..HEAD`):")
	return append(out, fencedList(g.log)...)
}

// fencedList is lines in a fence, at most handoffListMax, each cut to the wrap width.
func fencedList(lines []string) []string {
	if len(lines) == 0 {
		return []string{"- none"}
	}
	out := []string{"```"}
	for _, ln := range lines[:min(len(lines), handoffListMax)] {
		out = append(out, textutil.CapRunes(ln, handoffWidth, "…"))
	}
	out = append(out, "```")
	if len(lines) > handoffListMax {
		out = append(out, fmt.Sprintf("- truncated at %d lines", handoffListMax))
	}
	return out
}

// idComment is a bank entry's trailing "<!-- id:9c2d7e41 -->".
var idComment = sync.OnceValue(func() *regexp.Regexp {
	return regexp.MustCompile(`\s*<!--\s*id:([0-9a-z]+)\s*-->\s*$`)
})

// rulingsSection is the decision log's newest entries (the file is newest first), titles and ids only.
func rulingsSection(b Bank) []string {
	out := []string{"## Owner rulings (newest " + strconv.Itoa(handoffRulingsMax) + ")"}
	data, err := os.ReadFile(b.Path("decisionLog.md"))
	if err == nil {
		_, body := textutil.StripFrontMatter(data)
		for _, h := range textutil.Headings(body) {
			if h.Level != 2 || len(out) > handoffRulingsMax {
				continue
			}
			title, id := h.Text, ""
			if m := idComment().FindStringSubmatchIndex(title); m != nil {
				title, id = title[:m[0]], " (id "+title[m[2]:m[3]]+")"
			}
			out = append(out, "- "+strings.TrimSpace(title)+id)
		}
	}
	if len(out) == 1 {
		out = append(out, "- none")
	}
	return out
}

// pointersSection names the fresh model-written handoff, today's newest plan and today's reports.
func pointersSection(b Bank, now time.Time) []string {
	handoff := cmp.Or(newestHandoff(b, now, 24*time.Hour), "none")
	dir := filepath.Join(paths.ConfigDir(), "plans")
	plans := append(transcript.GlobIn(dir, "*.md"), transcript.GlobIn(dir, "*/*.md")...)
	plan, _ := newestFile(todays(plans, now), now, 24*time.Hour)
	var reports []string
	for _, p := range todays(ownedFiles(b, "reports"), now) {
		reports = append(reports, filepath.Base(p))
	}
	slices.Sort(reports)
	line := fmt.Sprintf("- Reports today (%d)", len(reports))
	if len(reports) > 0 {
		line += ": " + strings.Join(reports[:min(len(reports), handoffReportsMax)], ", ")
	}
	return []string{"## Pointers", "- Model-written handoff (under 24 h): " + handoff,
		"- Plan modified today: " + cmp.Or(plan, "none"), line}
}

// todays keeps the files modified on now's local date.
func todays(files []string, now time.Time) []string {
	day := now.Format("2006-01-02")
	return slices.DeleteFunc(slices.Clone(files), func(p string) bool {
		fi, err := os.Stat(p)
		return err != nil || fi.ModTime().Format("2006-01-02") != day
	})
}

// wrapHandoff wraps a prose or list line at handoffWidth on spaces; fence and code lines pass unchanged.
func wrapHandoff(line string) []string {
	if utf8.RuneCountInString(line) <= handoffWidth || !strings.HasPrefix(line, "- ") && !strings.HasPrefix(line, "Generated") {
		return []string{line}
	}
	marker, indent := "", ""
	if strings.HasPrefix(line, "- ") {
		marker, indent = "- ", "  "
	}
	var out []string
	cur := ""
	for w := range strings.FieldsSeq(line[len(marker):]) {
		switch {
		case cur == "":
			cur = w
		case utf8.RuneCountInString(cur)+1+utf8.RuneCountInString(w)+len(indent) > handoffWidth:
			out, cur = append(out, cur), w
		default:
			cur += " " + w
		}
	}
	out = append(out, cur)
	for i := range out {
		out[i] = indent + out[i]
	}
	out[0] = marker + strings.TrimPrefix(out[0], indent)
	return out
}
