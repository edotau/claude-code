// TestAliasVerbCaseInsensitive pins that git's case-insensitive alias names expand to the real verb.
func TestAliasVerbCaseInsensitive(t *testing.T) {
	if got := collectGit("git -c alias.xx=reset XX --hard", "/w"); !reflect.DeepEqual(got, []gitCall{{"/w", "reset"}}) {
		t.Errorf("alias XX = %v, want reset", got)
	}
	if !gitCommitInvocation("git -c alias.ci=commit CI --allow-empty -m x") {
		t.Error("upper-case alias of commit not seen as a commit")
	}
}

// TestAttributionFooterCommit pins the footer patterns; the safety-scan wiring has its own test in internal/hooks.
func TestAttributionFooterCommit(t *testing.T) {
	cases := []struct {
		name string
		cmd  string
		want bool
	}{
		{"co-authored-by claude, mixed case", `git commit -m "feat: x" -m "Co-Authored-By: Claude <noreply@anthropic.com>"`, true},
		{"co-authored-by claude, lowercase", `git commit -m "co-authored-by: claude"`, true},
		{"co-authored-by claude, extra spaces before claude", `git commit -m "Co-Authored-By:   Claude Opus"`, true},
		{"generated with claude code, bracketed link", `git commit -F - <<'EOF'\nfeat: x\n\nGenerated with [Claude Code](https://claude.com/claude-code)\nEOF`, true},
		{"generated with claude code, no bracket", `git commit -m "Generated with Claude Code"`, true},
		{"heredoc body carries the footer", "git commit -m \"$(cat <<'EOF'\nfeat: x\n\nCo-Authored-By: Claude Opus <noreply@anthropic.com>\nEOF\n)\"", true},
		{"co-authored-by codex", `git commit -m "feat: x" -m "Co-authored-by: Codex <codex@openai.com>"`, true},
		{"generated by github copilot", `git commit -m "feat: x" -m "Generated by GitHub Copilot"`, true},
		{"footer in a commit nested too deep to inspect", "eval eval eval eval eval git commit -m 'Co-Authored-By: Claude'", true},
		{"plain commit, no footer", `git commit -m "feat: x"`, false},
		{"name prefix only, not an agent", `git commit -m "Co-Authored-By: Claudette <c@x>"`, false},
		{"footer names a human, not claude", `git commit -m "Co-Authored-By: Ada <a@x>"`, false},
		{"co-authored-by with no claude mention", `git commit -m "Co-Authored-By: Someone Else"`, false},
		{"claude mentioned but not as a footer", `git commit -m "ask claude about this"`, false},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			if got := AttributionFooterCommit(c.cmd); got != c.want {
				t.Errorf("AttributionFooterCommit(%q) = %v, want %v", c.cmd, got, c.want)
			}
		})
	}
}

func TestAttributionFooterHidden(t *testing.T) {
	for cmd, want := range map[string]bool{
		`git commit -m "x Co-Authored-By: Cl""aude"`:                        true,
		`git commit -m $'Co-Authored-By:\x20Claude'`:                        true,
		`git commit -m "Generated with [Claude](https://c.ai)"`:             true,
		`git commit -m "Co-Authored-By: Anthropic <a@b>"`:                   true,
		`git -c alias.ci=commit ci -m "Co-Authored-By: Claude"`:             true,
		`git $(echo commit) -m "Co-Authored-By: Claude"`:                    true,
		`setsid sh -c 'git commit -m "Co-Authored-By: Claude"'`:             true,
		`git commit -m "$(printf 'Co-Authored-By: %s' Claude)"`:             true,
		`git commit -m "mention co-authored-by docs"`:                       false,
		"git commit -m \"$(cat <<'EOF'\nfix: co-authored-by docs\nEOF\n)\"": false,
		`echo $(date); git commit -m "mention co-authored-by docs"`:         false,
		`git commit -m "fix: x"`:                                            false,
	} {
		if got := AttributionFooterCommit(cmd); got != want {
			t.Errorf("AttributionFooterCommit(%q) = %v, want %v", cmd, got, want)
		}
	}
}

func TestReadOnlyGitLeadingNoPager(t *testing.T) {
	for cmd, want := range map[string]bool{
		"git --no-pager status":                           true,
		"git --no-pager status --short --branch":          true,
		"git --no-pager diff --no-ext-diff --no-textconv": true,
		"git --no-pager push":                             false,
		"git --no-pager --no-pager status":                false,
		"git --no-pager=x status":                         false,
		"git -c core.pager=x status":                      false,
		"git --config-env=a=b status":                     false,
		"git --paginate status":                           false,
		"git --no-pager":                                  false,
	} {
		if got := ReadOnlyGit(cmd); got != want {
			t.Errorf("ReadOnlyGit(%q) = %v, want %v", cmd, got, want)
		}
	}
}

func TestReadOnlyGitRefusesOutsidePaths(t *testing.T) {
	for cmd, want := range map[string]bool{
		"git --no-pager diff --no-ext-diff --no-textconv /etc/hostname /etc/hosts":  false,
		"git --no-pager diff --no-ext-diff --no-textconv ../a ../b":                 false,
		"git --no-pager diff --no-ext-diff --no-textconv -- /etc/hostname":          false,
		"git --no-pager diff --no-ext-diff --no-textconv internal/shell/scope.go":   true,
		"git --no-pager log --no-ext-diff --no-textconv -- internal/shell/scope.go": true,
	} {
		if got := ReadOnlyGit(cmd); got != want {
			t.Errorf("ReadOnlyGit(%q) = %v, want %v", cmd, got, want)
		}
	}
}

// TestReadOnlyGitRefusesNoIndex pins that --no-index (reads outside the repo) is refused for diff and grep.
func TestReadOnlyGitRefusesNoIndex(t *testing.T) {
	for _, cmd := range []string{
		"git diff --no-ext-diff --no-textconv --no-index /etc/passwd /dev/null",
		"git grep --no-index -e secret /etc",
	} {
		if ReadOnlyGit(cmd) {
			t.Errorf("ReadOnlyGit(%q) = true", cmd)
		}
	}
}
