package shell

import "testing"

// TestAttributionFooterCommit pins the footer patterns; the safety-scan wiring has its own test in internal/hooks.
func TestAttributionFooterCommit(t *testing.T) {
	cases := []struct {
		name string
		cmd  string
		want bool
	}{
		{"co-authored-by claude, mixed case", `git commit -m "feat: x" -m "Co-Authored-By: Claude <noreply@anthropic.com>"`, true},
		{"co-authored-by claude, lowercase", `git commit -m "co-authored-by: claude"`, true},
		{"co-authored-by claude, extra spaces before claude", `git commit -m "Co-Authored-By:   Claude Opus"`, true},
		{"generated with claude code, bracketed link", `git commit -F - <<'EOF'\nfeat: x\n\nGenerated with [Claude Code](https://claude.com/claude-code)\nEOF`, true},
		{"generated with claude code, no bracket", `git commit -m "Generated with Claude Code"`, true},
		{"heredoc body carries the footer", "git commit -m \"$(cat <<'EOF'\nfeat: x\n\nCo-Authored-By: Claude Opus <noreply@anthropic.com>\nEOF\n)\"", true},
		{"co-authored-by codex", `git commit -m "feat: x" -m "Co-authored-by: Codex <codex@openai.com>"`, true},
		{"generated by github copilot", `git commit -m "feat: x" -m "Generated by GitHub Copilot"`, true},
		{"plain commit, no footer", `git commit -m "feat: x"`, false},
		{"name prefix only, not an agent", `git commit -m "Co-Authored-By: Claudette <c@x>"`, false},
		{"footer names a human, not claude", `git commit -m "Co-Authored-By: Ada <a@x>"`, false},
		{"co-authored-by with no claude mention", `git commit -m "Co-Authored-By: Someone Else"`, false},
		{"claude mentioned but not as a footer", `git commit -m "ask claude about this"`, false},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			if got := AttributionFooterCommit(c.cmd); got != c.want {
				t.Errorf("AttributionFooterCommit(%q) = %v, want %v", c.cmd, got, c.want)
			}
		})
	}
}
