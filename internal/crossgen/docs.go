package crossgen

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// DocsBanner is stamped at the top of every generated vendor instruction file; prune/KEEP logic keys on it.
const DocsBanner = "<!-- GENERATED by claude-code agents sync — edit CLAUDE.md + agents/, then re-run. -->"

// instructionFiles maps a vendor to the global instruction file its CLI reads from $HOME (relative path).
// Claude Code reads CLAUDE.md itself and OpenCode reads ~/.claude/CLAUDE.md natively, so only codex, gemini and
// copilot (`copilot instruction list` → "Personal instructions") get a render; nothing is written at the config
// root (Claude Code would load a root AGENTS.md as a second copy of CLAUDE.md in every session).
var instructionFiles = map[string]string{
	"codex":   filepath.Join(".codex", "AGENTS.md"),
	"copilot": filepath.Join(".copilot", "copilot-instructions.md"),
	"gemini":  filepath.Join(".gemini", "GEMINI.md"),
}

// renderDocs renders banner + CLAUDE.md verbatim + a sorted `## Agents` index for the harness at root, from
// agents (the caller's single DiscoverAgents pass); ok is false when root has no CLAUDE.md (a bare box
// renders no roster docs).
func renderDocs(root string, agents []Source) (content string, ok bool, err error) {
	conventions, err := os.ReadFile(filepath.Join(root, "CLAUDE.md"))
	if os.IsNotExist(err) {
		return "", false, nil
	}
	if err != nil {
		return "", false, fmt.Errorf("read CLAUDE.md: %w", err)
	}
	var b strings.Builder
	b.WriteString(DocsBanner + "\n\n")
	b.WriteString(strings.TrimRight(string(conventions), "\n"))
	b.WriteString("\n\n## Agents\n\n")
	for _, a := range agents {
		tier := toString(a.frontmatter["model"])
		if tier == "" {
			tier = "inherit"
		}
		row := fmt.Sprintf("- **%s** (`%s`)", a.Name(), tier)
		if desc := firstSentence(cleanDescription(toString(a.frontmatter["description"]))); desc != "" {
			row += " — " + desc
		}
		b.WriteString(row + "\n")
	}
	return b.String(), true, nil
}
