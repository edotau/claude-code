package crossgen

import (
	"fmt"
	"io"
	"os"
	"path/filepath"
	"strings"

	"github.com/edotau/claude-code/internal/paths"
)

// DocsBanner is stamped at the top of every generated AGENTS.md/GEMINI.md.
const DocsBanner = "<!-- GENERATED by claude-code agents docs — edit CLAUDE.md + agents/, then re-run. -->"

// outputFiles are written byte-identical: AGENTS.md is the cross-tool standard, GEMINI.md Gemini CLI's context file.
var outputFiles = []string{"AGENTS.md", "GEMINI.md"}

// DocsOptions configures a docs render.
type DocsOptions struct {
	Check  bool      // exit 1 if a generated file drifted; never writes
	DryRun bool      // preview without writing
	Out    io.Writer // status lines and preview; nil → os.Stdout
}

// renderDocs renders banner + CLAUDE.md verbatim + a sorted `## Agents` index for the harness at root.
func renderDocs(root string) (string, error) {
	conventions, err := os.ReadFile(filepath.Join(root, "CLAUDE.md"))
	if err != nil {
		return "", fmt.Errorf("read CLAUDE.md: %w", err)
	}
	agents, err := DiscoverAgents(filepath.Join(root, "agents"))
	if err != nil {
		return "", err
	}
	var b strings.Builder
	b.WriteString(DocsBanner + "\n\n")
	b.WriteString(strings.TrimRight(string(conventions), "\n"))
	b.WriteString("\n\n## Agents\n\n")
	for _, a := range agents {
		tier := toString(a.frontmatter["model"])
		if tier == "" {
			tier = "inherit"
		}
		row := fmt.Sprintf("- **%s** (`%s`)", a.Name(), tier)
		if desc := firstSentence(cleanDescription(toString(a.frontmatter["description"]))); desc != "" {
			row += " — " + desc
		}
		b.WriteString(row + "\n")
	}
	return b.String(), nil
}

// RenderDocs renders AGENTS.md and GEMINI.md at paths.ConfigDir(); exit 0 ok, 1 on drift (--check) or error.
func RenderDocs(opts DocsOptions) int {
	out := opts.Out
	if out == nil {
		out = os.Stdout
	}
	root := paths.ConfigDir()
	content, err := renderDocs(root)
	if err != nil {
		fmt.Fprintln(os.Stderr, "docs:", err)
		return 1
	}

	if opts.Check {
		drifted := 0
		for _, name := range outputFiles {
			if existing, err := os.ReadFile(filepath.Join(root, name)); err != nil || string(existing) != content {
				fmt.Fprintf(os.Stderr, "DRIFT: %s is out of date — run `claude-code agents docs`\n", name)
				drifted++
			}
		}
		if drifted > 0 {
			return 1
		}
		fmt.Fprintf(out, "OK: %d generated file(s) up to date\n", len(outputFiles))
		return 0
	}
	if opts.DryRun {
		fmt.Fprintf(out, "DRY-RUN — would write: %s\n--- preview ---\n%s", strings.Join(outputFiles, ", "), content)
		return 0
	}
	for _, name := range outputFiles {
		wrote, err := paths.WriteIfChanged(filepath.Join(root, name), []byte(content), 0o644)
		if err != nil {
			fmt.Fprintln(os.Stderr, "docs:", err)
			return 1
		}
		if wrote {
			fmt.Fprintf(out, "wrote %s\n", name)
		} else {
			fmt.Fprintf(out, "OK    %s (unchanged)\n", name)
		}
	}
	return 0
}
