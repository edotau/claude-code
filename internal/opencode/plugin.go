// pluginJS is the plugin template; renderPlugin fills in __BIN__ and __MODULES__ (JSON literals) and __HOSTEDENV__.
const pluginJS = `// Generated by claude-code (internal/opencode/plugin.go) for one opencode launch; do not edit.
import { execFile, execFileSync } from "node:child_process"

const BIN = __BIN__
const MODULES = __MODULES__
const TOOLS = { bash: "Bash", edit: "Edit", write: "Write", multiedit: "Edit", read: "Read", webfetch: "WebFetch",
  apply_patch: "Edit", glob: "Glob", grep: "Grep", list: "Read" }
const KEYS = { filePath: "file_path", oldString: "old_string", newString: "new_string", replaceAll: "replace_all" }

function claudeInput(args) {
  const out = {}
  for (const [k, v] of Object.entries(args ?? {})) out[KEYS[k] ?? k] = v
  return out
}

// denied is the block reason for deny and ask decisions ("" to allow), or null when stdout is not a hook document.
function denied(stdout) {
  if (!stdout.trim()) return "" // a silent allow prints nothing
  let out
  try {
    out = JSON.parse(stdout).hookSpecificOutput ?? {}
  } catch {
    return null
  }
  if (out.permissionDecision === "ask") return out.permissionDecisionReason || "approval required; blocked"
  return out.permissionDecision === "deny" ? (out.permissionDecisionReason || "denied") : ""
}

// incomplete blocks a module that failed closed, else allows the call with a note.
function incomplete(m, why) {
  if (m.failClosed) return m.name + " did not complete (" + why + "); blocked"
  console.error("claude-code plugin: " + m.name + " did not complete (" + why + "); allowed")
  return ""
}

// verdict is the block reason for one module, or "" to let the call run.
function verdict(m, payload) {
  try {
    const reason = denied(execFileSync(BIN, ["hook", "PreToolUse", "--" + m.name],
      { input: payload, timeout: m.budgetMs, encoding: "utf8", stdio: ["pipe", "pipe", "pipe"] }))
    return reason ?? incomplete(m, "malformed output")
  } catch (err) {
    if (err.status === 2) return String(err.stderr ?? "").trim() || m.name + " blocked the call"
    return incomplete(m, err.signal ? "timed out (" + err.signal + ")" : (err.code ?? "exit " + err.status))
  }
}

let last = ""
const updating = new Set()
const HOSTED = process.env.__HOSTEDENV__ === "1"

// eventPayload is the Claude-shaped document for a Stop/SessionEnd hook; harness_agent tells memhook to export the session.
function eventPayload(name, sid, cwd) {
  return JSON.stringify({ hook_event_name: name, session_id: sid, cwd, harness_agent: "opencode" })
}

export const ClaudeCodeHarness = async ({ directory }) => ({
  "tool.execute.before": async (input, output) => {
    const tool = TOOLS[input.tool]
    if (!tool) return
    const payload = JSON.stringify({ hook_event_name: "PreToolUse", tool_name: tool,
      tool_input: claudeInput(output.args), cwd: directory, session_id: input.sessionID })
    for (const m of MODULES) {
      if (!new RegExp("^(?:" + m.matcher + ")$", "i").test(tool)) continue
      const reason = verdict(m, payload)
      if (reason) throw new Error(reason)
    }
  },
  // session.idle -> hook Stop --memory-update (async, one in flight per session); session.deleted / instance disposed -> hook SessionEnd --memory-end.
  event: async ({ event }) => {
    if (HOSTED) return // the headless host fires Stop/SessionEnd itself
    const sid = event.properties?.sessionID ?? event.properties?.info?.id
    if (event.type === "session.idle" && sid) {
      last = sid
      if (updating.has(sid)) return
      updating.add(sid)
      const p = execFile(BIN, ["hook", "Stop", "--memory-update"], { timeout: 20000, stdio: "pipe" }, () => updating.delete(sid))
      p.stdin?.end(eventPayload("Stop", sid, directory))
    } else if ((event.type === "session.deleted" || event.type === "server.instance.disposed") && (sid ?? last)) {
      try {
        execFileSync(BIN, ["hook", "SessionEnd", "--memory-end"],
          { input: eventPayload("SessionEnd", sid ?? last, directory), timeout: 15000, stdio: ["pipe", "ignore", "ignore"] })
      } catch {}
      last = ""
    }
  },
})
`

// hostedEnv marks a child whose Go host fires Stop/SessionEnd itself, so the plugin must not fire them too.
const hostedEnv = "HARNESS_OPENCODE_HOSTED"

// withHostedMarker is env plus the hostedEnv marker when a host runs this dispatch (nil host: the plugin owns the memory hooks).
func withHostedMarker(env []string, h *hookHost) []string {
	if h == nil {
		return env
	}
	return append(slices.Clone(env), hostedEnv+"=1")
}

// pluginFailClosed are the plugin modules whose timeout or crash blocks the call; the rest fail open with a note.
var pluginFailClosed = []string{"permission-gate", "safety-scan"}

// pluginModule is one hook the plugin runs before an opencode tool call, as the JS reads it.
type pluginModule struct {
	Name       string `json:"name"`
	Matcher    string `json:"matcher"`
	BudgetMs   int64  `json:"budgetMs"`
	FailClosed bool   `json:"failClosed"`
}

// pluginModules are SpecsFor("opencode", "plugin"): the PreToolUse guards the plugin runs in place of the host.
func pluginModules() []pluginModule {
	var out []pluginModule
	for _, s := range settings.SpecsFor("opencode", "plugin") {
		if s.Event != settings.EventPreToolUse {
			continue
		}
		out = append(out, pluginModule{Name: s.Name, Matcher: s.Matcher, BudgetMs: s.Budget.Milliseconds(),
			FailClosed: slices.Contains(pluginFailClosed, s.Name)})
	}
	return out
}

// renderPlugin is the plugin's JS: tool.execute.before runs `<bin> hook PreToolUse --<module>` per matching module.
func renderPlugin(bin string, mods []pluginModule) ([]byte, error) {
	binJSON, err := json.Marshal(bin)
	if err != nil {
		return nil, err
	}
	modsJSON, err := json.Marshal(mods)
	if err != nil {
		return nil, err
	}
	r := strings.NewReplacer("__BIN__", string(binJSON), "__MODULES__", string(modsJSON), "__HOSTEDENV__", hostedEnv)
	return []byte(r.Replace(pluginJS)), nil
}

// writePlugin renders the plugin (0600, content-hashed name: launches on different binaries never collide); file:// URL.
func writePlugin() (string, error) {
	bin, err := paths.SelfBinary()
	if err != nil {
		bin = filepath.Join(paths.BinDir(), "claude-code")
	}
	body, err := renderPlugin(bin, pluginModules())
	if err != nil {
		return "", err
	}
	sum := sha256.Sum256(body)
	dest := filepath.Join(paths.StateDir(), "opencode", "harness-hooks-"+hex.EncodeToString(sum[:6])+".js")
	if _, err := paths.WriteIfChanged(dest, body, 0o600); err != nil {
		return "", fmt.Errorf("opencode plugin: %w", err)
	}
	prunePlugins(dest, time.Now().Add(-pluginGrace))
	return "file://" + filepath.ToSlash(dest), nil
}

// pluginGrace keeps a superseded plugin file, so an opencode process launched from another build still finds its own.
const pluginGrace = time.Hour

// prunePlugins removes the harness-hooks-*.js files beside keep that were last written before cutoff; best effort.
func prunePlugins(keep string, cutoff time.Time) {
	old, _ := filepath.Glob(filepath.Join(filepath.Dir(keep), "harness-hooks-*.js"))
	for _, f := range old {
		if info, err := os.Stat(f); f != keep && err == nil && info.ModTime().Before(cutoff) {
			_ = os.Remove(f) // a racing prune or a file opencode still holds is fine to leave
		}
	}
}

// opencodeApplyPlugin adds the harness plugin to a tools-on, non --pure run's config; plugged reports the injection.
func opencodeApplyPlugin(env []string, req agent.RunOptions) (out []string, plugged bool, err error) {
	if !req.Tools || req.SafeMode { // --pure loads no external plugin
		return env, false, nil
	}
	url, err := writePlugin()
	if err != nil {
		return nil, false, err
	}
	out, err = mutateOpencodeConfigEnv(env, false, func(cfg map[string]any) {
		addPlugin(cfg, url)
	})
	return out, err == nil, err
}

// addPlugin appends the plugin url to cfg's plugin list, keeping the user's own entries.
func addPlugin(cfg map[string]any, url string) {
	list, _ := cfg["plugin"].([]any)
	cfg["plugin"] = append(list, url)
}
