// pluginJS is the plugin template; __BIN__ and __MODULES__ are JSON literals filled in by renderPlugin.
const pluginJS = `// Generated by claude-code (internal/opencode/plugin.go) for one opencode launch; do not edit.
import { execFileSync } from "node:child_process"

const BIN = __BIN__
const MODULES = __MODULES__
const TOOLS = { bash: "Bash", edit: "Edit", write: "Write", multiedit: "MultiEdit", read: "Read", webfetch: "WebFetch" }
const KEYS = { filePath: "file_path", oldString: "old_string", newString: "new_string", replaceAll: "replace_all" }

function claudeInput(args) {
  const out = {}
  for (const [k, v] of Object.entries(args ?? {})) out[KEYS[k] ?? k] = v
  return out
}

// denied reads a Claude-shaped hook document on stdout: a deny decision blocks like exit 2 does.
function denied(stdout) {
  try {
    const out = JSON.parse(stdout).hookSpecificOutput ?? {}
    return out.permissionDecision === "deny" ? (out.permissionDecisionReason || "denied") : ""
  } catch {
    return ""
  }
}

// verdict is the block reason for one module, or "" to let the call run.
function verdict(m, payload) {
  try {
    const stdout = execFileSync(BIN, ["hook", "PreToolUse", "--" + m.name],
      { input: payload, timeout: m.budgetMs, encoding: "utf8", stdio: ["pipe", "pipe", "pipe"] })
    return denied(stdout)
  } catch (err) {
    if (err.status === 2) return String(err.stderr ?? "").trim() || m.name + " blocked the call"
    const why = err.signal ? "timed out (" + err.signal + ")" : (err.code ?? "exit " + err.status)
    if (m.failClosed) return m.name + " did not complete (" + why + "); blocked"
    console.error("claude-code plugin: " + m.name + " did not complete (" + why + "); allowed")
    return ""
  }
}

export const ClaudeCodeHarness = async ({ directory }) => ({
  "tool.execute.before": async (input, output) => {
    const tool = TOOLS[input.tool]
    if (!tool) return
    const payload = JSON.stringify({ hook_event_name: "PreToolUse", tool_name: tool,
      tool_input: claudeInput(output.args), cwd: directory, session_id: input.sessionID })
    for (const m of MODULES) {
      if (!new RegExp("^(?:" + m.matcher + ")$", "i").test(tool)) continue
      const reason = verdict(m, payload)
      if (reason) throw new Error(reason)
    }
  },
  // SEAM (M-1, not wired): session.idle -> hook Stop --memory-update, session end -> hook SessionEnd --memory-end.
  // event: async ({ event }) => {},
})
`

// pluginFailClosed are the plugin modules whose timeout or crash blocks the call; the rest fail open with a note.
var pluginFailClosed = []string{"permission-gate", "safety-scan"}

// pluginModule is one hook the plugin runs before an opencode tool call, as the JS reads it.
type pluginModule struct {
	Name       string `json:"name"`
	Matcher    string `json:"matcher"`
	BudgetMs   int64  `json:"budgetMs"`
	FailClosed bool   `json:"failClosed"`
}

// pluginModules are SpecsFor("opencode", "plugin"): the PreToolUse guards the plugin runs in place of the host.
func pluginModules() []pluginModule {
	var out []pluginModule
	for _, s := range settings.SpecsFor("opencode", "plugin") {
		if s.Event != settings.EventPreToolUse {
			continue
		}
		out = append(out, pluginModule{Name: s.Name, Matcher: s.Matcher, BudgetMs: s.Budget.Milliseconds(),
			FailClosed: slices.Contains(pluginFailClosed, s.Name)})
	}
	return out
}

// renderPlugin is the plugin's JS: tool.execute.before runs `<bin> hook PreToolUse --<module>` per matching module.
func renderPlugin(bin string, mods []pluginModule) ([]byte, error) {
	binJSON, err := json.Marshal(bin)
	if err != nil {
		return nil, err
	}
	modsJSON, err := json.Marshal(mods)
	if err != nil {
		return nil, err
	}
	r := strings.NewReplacer("__BIN__", string(binJSON), "__MODULES__", string(modsJSON))
	return []byte(r.Replace(pluginJS)), nil
}

// writePlugin renders the plugin (0600, content-hashed name: launches on different binaries never collide); file:// URL.
func writePlugin() (string, error) {
	bin, err := agent.SelfBinary()
	if err != nil {
		bin = filepath.Join(paths.BinDir(), "claude-code")
	}
	body, err := renderPlugin(bin, pluginModules())
	if err != nil {
		return "", err
	}
	sum := sha256.Sum256(body)
	dest := filepath.Join(paths.StateDir(), "opencode", "harness-hooks-"+hex.EncodeToString(sum[:6])+".js")
	if _, err := paths.WriteIfChanged(dest, body, 0o600); err != nil {
		return "", fmt.Errorf("opencode plugin: %w", err)
	}
	return "file://" + filepath.ToSlash(dest), nil
}

// opencodeApplyPlugin adds the harness plugin to a tools-on, non --pure run's config; plugged reports the injection.
func opencodeApplyPlugin(env []string, req agent.RunOptions) (out []string, plugged bool, err error) {
	if !req.Tools || req.SafeMode { // --pure loads no external plugin
		return env, false, nil
	}
	url, err := writePlugin()
	if err != nil {
		return nil, false, err
	}
	out, err = mutateOpencodeConfigEnv(env, false, func(cfg map[string]any) {
		list, _ := cfg["plugin"].([]any)
		cfg["plugin"] = append(list, url)
	})
	return out, err == nil, err
}
