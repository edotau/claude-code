// TestAttributionFooterBlocked pins the footer patterns; the safety-scan wiring has its own test below.
func TestAttributionFooterBlocked(t *testing.T) {
	cases := []struct {
		name string
		cmd  string
		want bool
	}{
		{"co-authored-by claude, mixed case", `git commit -m "feat: x" -m "Co-Authored-By: Claude <noreply@anthropic.com>"`, true},
		{"co-authored-by claude, lowercase", `git commit -m "co-authored-by: claude"`, true},
		{"co-authored-by claude, extra spaces before claude", `git commit -m "Co-Authored-By:   Claude Opus"`, true},
		{"generated with claude code, bracketed link", `git commit -F - <<'EOF'\nfeat: x\n\nGenerated with [Claude Code](https://claude.com/claude-code)\nEOF`, true},
		{"generated with claude code, no bracket", `git commit -m "Generated with Claude Code"`, true},
		{"heredoc body carries the footer", "git commit -m \"$(cat <<'EOF'\nfeat: x\n\nCo-Authored-By: Claude Opus <noreply@anthropic.com>\nEOF\n)\"", true},
		{"co-authored-by codex", `git commit -m "feat: x" -m "Co-authored-by: Codex <codex@openai.com>"`, true},
		{"generated by github copilot", `git commit -m "feat: x" -m "Generated by GitHub Copilot"`, true},
		{"plain commit, no footer", `git commit -m "feat: x"`, false},
		{"name prefix only, not an agent", `git commit -m "Co-Authored-By: Claudette <c@x>"`, false},
		{"footer names a human, not claude", `git commit -m "Co-Authored-By: Ada <a@x>"`, false},
		{"co-authored-by with no claude mention", `git commit -m "Co-Authored-By: Someone Else"`, false},
		{"claude mentioned but not as a footer", `git commit -m "ask claude about this"`, false},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			if got := attributionFooterBlocked(c.cmd); got != c.want {
				t.Errorf("attributionFooterBlocked(%q) = %v, want %v", c.cmd, got, c.want)
			}
		})
	}
}

// TestSafetyScanBlocksAttributionFooterCommit: a footer commit in any repo blocks with a reason; the rest proceeds.
func TestSafetyScanBlocksAttributionFooterCommit(t *testing.T) {
	t.Setenv("CLAUDE_CONFIG_DIR", t.TempDir())
	otherRepo := t.TempDir() // not the harness tree: the contract is "in any repo"
	cases := []struct {
		name string
		cmd  string
		want int
	}{
		{
			"inline -m footer",
			`git commit -m "feat: x" -m "Co-Authored-By: Claude <noreply@anthropic.com>"`,
			ExitBlock,
		},
		{
			"heredoc -m footer",
			"git commit -m \"$(cat <<'EOF'\nfeat: x\n\nCo-Authored-By: Claude Opus <noreply@anthropic.com>\nEOF\n)\"",
			ExitBlock,
		},
		{
			"-C other repo, -F heredoc, generated-with footer",
			"git -C " + otherRepo + " commit -F - <<'EOF'\nfeat: x\n\nGenerated with [Claude Code](https://claude.com/claude-code)\nEOF",
			ExitBlock,
		},
		{
			"cd into other repo first",
			"cd " + otherRepo + " && git commit -m \"feat: x\" -m \"Co-Authored-By: Claude\"",
			ExitBlock,
		},
		{
			"plain commit proceeds",
			`git commit -m "feat: x"`,
			ExitProceed,
		},
		{
			"grep for the phrase proceeds (not a commit)",
			`git log --grep "Co-Authored-By: Claude"`,
			ExitProceed,
		},
		{
			"echo with no commit proceeds",
			`echo "Co-Authored-By: Claude"`,
			ExitProceed,
		},
		{
			"footer naming a human proceeds",
			`git commit -m "feat: x" -m "Co-Authored-By: Ada <a@x>"`,
			ExitProceed,
		},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			var errb bytes.Buffer
			if got := SafetyScan(bashPayload(c.cmd), io.Discard, &errb); got != c.want {
				t.Errorf("%q: got %d want %d (stderr=%s)", c.cmd, got, c.want, errb.String())
			}
			if c.want == ExitBlock && !strings.Contains(strings.ToLower(errb.String()), "attribution") {
				t.Errorf("%q: block reason missing 'attribution': %s", c.cmd, errb.String())
			}
		})
	}
}

// TestSafetyScanAttributionFooterCopilotShape: the Copilot payload gets the reason as permissionDecisionReason.
func TestSafetyScanAttributionFooterCopilotShape(t *testing.T) {
	t.Setenv("CLAUDE_CONFIG_DIR", t.TempDir())
	cmd := `git commit -m "feat: x" -m "Co-Authored-By: Claude <noreply@anthropic.com>"`
	payload := copilotBashPayload(cmd)
	var out, errb bytes.Buffer
	if got := SafetyScan(payload, &out, &errb); got != ExitBlock {
		t.Fatalf("%q: got %d want ExitBlock (out=%s err=%s)", cmd, got, out.String(), errb.String())
	}
	if !strings.Contains(strings.ToLower(out.String()), "attribution") {
		t.Errorf("permissionDecisionReason missing 'attribution': %s", out.String())
	}
}

// copilotBashPayload mirrors the Copilot shape used by TestSafetyScanChecksExecutedHeredocBodiesCopilot.
func copilotBashPayload(cmd string) io.Reader {
	b, _ := json.Marshal(map[string]any{
		"sessionId": "x", "toolName": "Bash", "toolArgs": map[string]string{"command": cmd},
	})
	return strings.NewReader(string(b))
}
