// Package completion renders and installs the bash tab-completion shim for claude-code and its bare
// vendor shims (claude, codex, gemini, opencode, copilot — see internal/launch.ShimNames). It is pure
// string/file logic with no verb dispatch, so it carries zero risk of launching an agent CLI or
// touching the network; that property is what lets internal/launch.Install call it unconditionally.
package completion

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// funcName turns a hyphenated binary name into a valid-looking bash identifier for readability.
func funcName(bin string) string { return "_" + strings.ReplaceAll(bin, "-", "_") }

// Script renders the bash `complete` registrations: bin itself, plus its bare vendor shims (a shim
// name with nothing installed under it is an inert registration, not an error).
func Script(bin string, shims []string) string {
	fn := funcName(bin)
	return fmt.Sprintf(`# bash completion for %[1]s — generated by '%[1]s completion'; regenerate, don't edit.
%[2]s() {
    COMPREPLY=()
    local line
    while IFS= read -r line; do COMPREPLY+=("$line"); done \
        < <("${COMP_WORDS[0]}" __complete "${COMP_WORDS[@]:1:COMP_CWORD}" 2>/dev/null)
}
complete -o default -F %[2]s %[1]s

# A bare vendor shim IS that verb (busybox dispatch) — complete it as '%[1]s <verb> …'.
%[2]s_verb() {
    local verb=${COMP_WORDS[0]##*/}
    COMPREPLY=()
    local line
    while IFS= read -r line; do COMPREPLY+=("$line"); done \
        < <(%[1]s __complete "$verb" "${COMP_WORDS[@]:1:COMP_CWORD}" 2>/dev/null)
}
complete -o default -F %[2]s_verb %[3]s
`, bin, fn, strings.Join(shims, " "))
}

// Dir resolves bash-completion's lazy-load dir per its own convention: BASH_COMPLETION_USER_DIR (if
// set) names the base dir directly; otherwise XDG_DATA_HOME/bash-completion, falling back to
// ~/.local/share/bash-completion. claude-dbx's completion only checked XDG_DATA_HOME — a user with
// BASH_COMPLETION_USER_DIR set (common on non-default bash-completion installs) got silently ignored.
func Dir() (string, error) {
	if dir := os.Getenv("BASH_COMPLETION_USER_DIR"); dir != "" {
		return filepath.Join(dir, "completions"), nil
	}
	dataHome := os.Getenv("XDG_DATA_HOME")
	if dataHome == "" {
		home, err := os.UserHomeDir()
		if err != nil {
			return "", err
		}
		dataHome = filepath.Join(home, ".local", "share")
	}
	return filepath.Join(dataHome, "bash-completion", "completions"), nil
}

// Install writes Script(bin, shims) to Dir()/bin, creating the dir if needed, and returns the path.
func Install(bin string, shims []string) (string, error) {
	dir, err := Dir()
	if err != nil {
		return "", err
	}
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return "", err
	}
	path := filepath.Join(dir, bin)
	if err := os.WriteFile(path, []byte(Script(bin, shims)), 0o644); err != nil {
		return "", err
	}
	return path, nil
}
